import { createHash } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { digest, sourceFingerprint, walk } from "./runtime-support.mjs";
const pkg = fileURLToPath(new URL("../", import.meta.url));
const zigRoot = fileURLToPath(new URL("../../../../zig/", import.meta.url));
const web = join(zigRoot, "pkg/inference/web");
const version = JSON.parse(await readFile(join(pkg, "package.json"))).version;
const zigVersion = JSON.parse(await readFile(join(zigRoot, "../scripts/ci/toolchain-policy.json")))
  .zig.version;
const files = ["inference-web.js", "inference-worker.js", "webgpu-ops.js"].map((name) =>
  join(web, name)
);
files.push(
  ...(await walk(join(web, "runtime"), [".js"])),
  ...(await walk(join(web, "shaders"), [".wgsl"]))
);
const sources = new Map();
const hash = createHash("sha256").update(
  `antfly-inference:${version}:protocol=1:abi=1:zig=${zigVersion}\0`
);
for (const path of await walk(join(pkg, "src"), [".ts"])) {
  hash.update(relative(pkg, path).replaceAll("\\", "/") + "\0");
  hash.update(await readFile(path));
}
const fingerprint = await sourceFingerprint(zigRoot);
hash.update(fingerprint);
for (const file of files.sort()) {
  const name = relative(web, file).replaceAll("\\", "/"),
    bytes = await readFile(file, "utf8");
  sources.set(name, bytes);
  hash.update(name + "\0" + bytes);
}
const compatibility = {
  manifestVersion: 1,
  protocolVersion: 1,
  clientVersion: version,
  extractionAbiVersion: 1,
  runtimeId: hash.digest("hex"),
};
const manifest = { ...compatibility, zigVersion, sourceFingerprint: fingerprint, files: [] };
const out = join(pkg, "dist/runtime-assets");
await rm(out, { recursive: true, force: true });
for (const [name, original] of sources) {
  const prepared = original.includes("__ANTFLY_RUNTIME_ID__")
    ? original.replaceAll("__ANTFLY_RUNTIME_ID__", compatibility.runtimeId)
    : name.endsWith(".js")
      ? original +
        `\nexport const INFERENCE_RUNTIME_ID = ${JSON.stringify(compatibility.runtimeId)};\n`
      : original;
  const path = join(out, name);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, prepared);
  manifest.files.push({
    path: name,
    sha256: digest(prepared),
    size_bytes: Buffer.byteLength(prepared),
  });
}
await writeFile(join(out, "runtime-manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
await writeFile(
  join(pkg, "dist/runtime-compatibility.js"),
  `// Generated by scripts/bundle-runtime.mjs.\nexport const RUNTIME_COMPATIBILITY = Object.freeze(${JSON.stringify(compatibility)});\n`
);
console.log(
  `Bundled runtime ${version}/${compatibility.runtimeId.slice(0, 16)} (${manifest.files.length} assets)`
);
