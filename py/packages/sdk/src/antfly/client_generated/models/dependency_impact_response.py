from __future__ import annotations

from collections.abc import Mapping
from typing import TYPE_CHECKING, Any, TypeVar

from attrs import define as _attrs_define
from attrs import field as _attrs_field

from ..types import UNSET, Unset

if TYPE_CHECKING:
    from ..models.dependency_impact_response_input import DependencyImpactResponseInput
    from ..models.dependency_impact_row import DependencyImpactRow


T = TypeVar("T", bound="DependencyImpactResponse")


@_attrs_define
class DependencyImpactResponse:
    """Reverse lineage of one source document: dependent artifact versions that
    consumed it, across every table whose enrichments read this table. A
    dependency establishes possible impact, not that regenerated bytes
    differ. `complete` is false whenever a depth or row budget was reached
    or a group could not be read.

        Attributes:
            input_ (DependencyImpactResponseInput):
            dependents (list[DependencyImpactRow]):
            complete (bool):
            traversal (str):
            semantics (str | Unset):
    """

    input_: DependencyImpactResponseInput
    dependents: list[DependencyImpactRow]
    complete: bool
    traversal: str
    semantics: str | Unset = UNSET
    additional_properties: dict[str, Any] = _attrs_field(init=False, factory=dict)

    def to_dict(self) -> dict[str, Any]:
        input_ = self.input_.to_dict()

        dependents = []
        for dependents_item_data in self.dependents:
            dependents_item = dependents_item_data.to_dict()
            dependents.append(dependents_item)

        complete = self.complete

        traversal = self.traversal

        semantics = self.semantics

        field_dict: dict[str, Any] = {}
        field_dict.update(self.additional_properties)
        field_dict.update(
            {
                "input": input_,
                "dependents": dependents,
                "complete": complete,
                "traversal": traversal,
            }
        )
        if semantics is not UNSET:
            field_dict["semantics"] = semantics

        return field_dict

    @classmethod
    def from_dict(cls: type[T], src_dict: Mapping[str, Any]) -> T:
        from ..models.dependency_impact_response_input import DependencyImpactResponseInput
        from ..models.dependency_impact_row import DependencyImpactRow

        d = dict(src_dict)
        input_ = DependencyImpactResponseInput.from_dict(d.pop("input"))

        dependents = []
        _dependents = d.pop("dependents")
        for dependents_item_data in _dependents:
            dependents_item = DependencyImpactRow.from_dict(dependents_item_data)

            dependents.append(dependents_item)

        complete = d.pop("complete")

        traversal = d.pop("traversal")

        semantics = d.pop("semantics", UNSET)

        dependency_impact_response = cls(
            input_=input_,
            dependents=dependents,
            complete=complete,
            traversal=traversal,
            semantics=semantics,
        )

        dependency_impact_response.additional_properties = d
        return dependency_impact_response

    @property
    def additional_keys(self) -> list[str]:
        return list(self.additional_properties.keys())

    def __getitem__(self, key: str) -> Any:
        return self.additional_properties[key]

    def __setitem__(self, key: str, value: Any) -> None:
        self.additional_properties[key] = value

    def __delitem__(self, key: str) -> None:
        del self.additional_properties[key]

    def __contains__(self, key: str) -> bool:
        return key in self.additional_properties
