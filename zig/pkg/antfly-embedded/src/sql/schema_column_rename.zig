//! Structured column rebinding for an unpublished rewrite successor. This is
//! not metadata-only ALTER: old packed layouts still own the predecessor name.
//! The caller must publish the matching immutable row transform atomically.
const std = @import("std");
const Value = std.json.Value;
const Limits = @import("immutable_plan.zig").Limits;

/// Schema-derived algebraic indexes are regenerated by normal table DDL.
/// Artifact indexes retain separately owned field bindings; do not silently
/// strand them when their source field is renamed. Conservative nonadmission
/// is intentional until those bindings participate in the rewrite cohort.
pub fn requireIndependentIndexes(a: std.mem.Allocator, json: []const u8, column: []const u8) !void {
    var parsed = try std.json.parseFromSlice(Value, a, json, .{});
    defer parsed.deinit();
    if (parsed.value != .object) return error.InvalidSqlBackendResponse;
    var entries = parsed.value.object.iterator();
    while (entries.next()) |entry| {
        const index = entry.value_ptr.*;
        if (std.mem.eql(u8, entry.key_ptr.*, "enrichments") or std.mem.eql(u8, entry.key_ptr.*, "resolvers")) {
            // These can own computed/dynamic bindings. Merely searching their
            // strings cannot prove independence of a source column. Empty
            // declarations are harmless; active producers need a bound cohort.
            const empty = switch (index) {
                .null => true,
                .array => index.array.items.len == 0,
                .object => index.object.count() == 0,
                else => false,
            };
            if (!empty) return error.UnsupportedSqlShape;
            continue;
        }
        if (index != .object) return error.InvalidSqlBackendResponse;
        const kind = index.object.get("type") orelse return error.InvalidSqlBackendResponse;
        if (kind != .string) return error.InvalidSqlBackendResponse;
        if (std.mem.eql(u8, kind.string, "algebraic")) continue;
        if (!std.mem.eql(u8, kind.string, "full_text")) return error.UnsupportedSqlShape;
        var budget: usize = 8192;
        if (try references(index, column, 0, &budget)) return error.UnsupportedSqlShape;
    }
}

fn fieldMatches(text: []const u8, column: []const u8) bool {
    return std.mem.eql(u8, text, column) or (std.mem.startsWith(u8, text, column) and text.len > column.len and text[column.len] == '.');
}
fn references(item: Value, column: []const u8, depth: usize, budget: *usize) anyerror!bool {
    if (depth > 64 or budget.* == 0) return error.SqlProgramLimitExceeded;
    budget.* -= 1;
    switch (item) {
        .string => |text| return fieldMatches(text, column),
        .array => |entries| for (entries.items) |entry| {
            if (try references(entry, column, depth + 1, budget)) return true;
        },
        .object => |object| {
            var entries = object.iterator();
            while (entries.next()) |entry| {
                if (std.mem.eql(u8, entry.key_ptr.*, "name") or std.mem.eql(u8, entry.key_ptr.*, "description") or std.mem.eql(u8, entry.key_ptr.*, "type")) continue;
                if (fieldMatches(entry.key_ptr.*, column) or try references(entry.value_ptr.*, column, depth + 1, budget)) return true;
            }
        },
        else => {},
    }
    return false;
}

const Rebind = struct {
    alloc: std.mem.Allocator,
    old: []const u8,
    new: []const u8,
    limits: Limits,
    visited: usize = 0,

    fn checkpoint(self: *@This(), depth: usize) !void {
        if (depth > self.limits.depth or self.visited >= self.limits.nodes) return error.SqlProgramLimitExceeded;
        self.visited += 1;
        if (self.limits.checkpoint) |check| try check(self.limits.checkpoint_context);
    }
    fn name(self: *@This(), item: *Value) !void {
        if (item.* != .string) return error.InvalidSqlBackendResponse;
        if (std.mem.eql(u8, item.string, self.old)) item.* = .{ .string = try self.alloc.dupe(u8, self.new) };
    }
    fn names(self: *@This(), object: *Value, key: []const u8) !void {
        if (object.object.getPtr(key)) |entries| {
            if (entries.* != .array) return error.InvalidSqlBackendResponse;
            for (entries.array.items) |*entry| {
                try self.checkpoint(0);
                try self.name(entry);
            }
        }
    }
    fn expression(self: *@This(), item: *Value, depth: usize) anyerror!void {
        try self.checkpoint(depth);
        switch (item.*) {
            .object => {
                const op = item.object.get("op") orelse return error.InvalidSqlBackendResponse;
                if (op != .string) return error.InvalidSqlBackendResponse;
                // A JSON literal may itself contain objects that look like IR.
                // Literal payloads and display strings are never identifiers.
                if (std.mem.eql(u8, op.string, "literal")) return;
                if (std.mem.eql(u8, op.string, "column")) {
                    try self.name(item.object.getPtr("column") orelse return error.InvalidSqlBackendResponse);
                    return;
                }
                for (item.object.values()) |*field| switch (field.*) {
                    .object => if (field.object.contains("op")) try self.expression(field, depth + 1),
                    .array => for (field.array.items) |*element| {
                        if (element.* == .object and element.object.contains("op")) try self.expression(element, depth + 1);
                    },
                    else => {},
                };
            },
            else => return error.InvalidSqlBackendResponse,
        }
    }
    fn declarations(self: *@This(), root: *Value, key: []const u8) !void {
        const entries = root.object.getPtr(key) orelse return;
        if (entries.* != .array) return error.InvalidSqlBackendResponse;
        for (entries.array.items) |*entry| {
            try self.checkpoint(0);
            if (entry.* != .object) return error.InvalidSqlBackendResponse;
            if (entry.object.getPtr("column")) |column| try self.name(column);
            try self.names(entry, "columns");
            try self.names(entry, "include_columns");
            if (entry.object.getPtr("without_overlaps_column")) |column| try self.name(column);
            if (entry.object.getPtr("expression")) |expr| try self.expression(expr, 0);
            for ([_][]const u8{ "keys", "where" }) |nested| {
                if (entry.object.getPtr(nested)) |items| {
                    if (items.* != .array) return error.InvalidSqlBackendResponse;
                    for (items.array.items) |*part| {
                        try self.checkpoint(0);
                        if (part.* != .object) return error.InvalidSqlBackendResponse;
                        if (part.object.getPtr("column")) |column| try self.name(column);
                        if (part.object.getPtr("expression")) |expr| try self.expression(expr, 0);
                    }
                }
            }
        }
    }
};

pub fn apply(a: std.mem.Allocator, root: *Value, old: []const u8, new: []const u8, limits: Limits) !void {
    if (std.mem.eql(u8, old, "_id") or std.mem.eql(u8, new, "_id")) return error.UnsupportedSqlShape;
    if (old.len == 0 or new.len == 0) return error.InvalidSqlSyntax;
    const props = try @import("schema_columns.zig").properties(root.*);
    const property = props.object.get(old) orelse return error.UndefinedColumn;
    if (props.object.contains(new)) return error.DuplicateSqlColumn;
    // FK column identities span tables. Do not locally rewrite a declaration
    // before the complete dependent cohort has its own column-name binding.
    if (root.object.get("foreign_keys")) |foreign| {
        if (foreign != .array) return error.InvalidSqlBackendResponse;
        for (foreign.array.items) |fk| {
            if (fk != .object) return error.InvalidSqlBackendResponse;
            for ([_][]const u8{ "child_columns", "parent_columns" }) |key| {
                const columns = fk.object.get(key) orelse return error.InvalidSqlBackendResponse;
                if (columns != .array) return error.InvalidSqlBackendResponse;
                for (columns.array.items) |column| {
                    if (column != .string) return error.InvalidSqlBackendResponse;
                    if (std.mem.eql(u8, column.string, old)) return error.UnsupportedSqlShape;
                }
            }
        }
    }
    var rebind: Rebind = .{ .alloc = a, .old = old, .new = new, .limits = limits };
    const default = root.object.get("default_type").?.string;
    const row = root.object.getPtr("document_schemas").?.object.getPtr(default).?.object.getPtr("schema").?;
    const properties = row.object.getPtr("properties").?;
    // Install the successor first; getOrPut can relocate map slots. All work
    // is inside the caller's unpublished arena and discarded on any failure.
    try properties.object.put(a, try a.dupe(u8, new), property);
    _ = properties.object.swapRemove(old);
    try rebind.names(row, "required");
    for ([_][]const u8{ "column_defaults", "generated_columns", "checks", "unique_constraints", "relational_indexes" }) |key|
        try rebind.declarations(root, key);
}

fn renameCase(backing: std.mem.Allocator) !void {
    var arena = std.heap.ArenaAllocator.init(backing);
    defer arena.deinit();
    const a = arena.allocator();
    const compiler = @import("compiler.zig");
    const ddl = @import("schema_ddl.zig");
    var create = try compiler.compile(a, "CREATE TABLE items(id bigint PRIMARY KEY,status text NOT NULL DEFAULT 'status', upper_status text GENERATED ALWAYS AS (upper(status)) STORED, CONSTRAINT status_check CHECK(status <> 'bad'))", .{});
    defer create.deinit();
    const json = try @import("ddl_runtime.zig").createSchemaAlloc(a, create.statement.create_table);
    var schema = try std.json.parseFromSliceLeaky(Value, a, json, .{ .parse_numbers = false });
    var index = try compiler.compile(a, "CREATE INDEX status_index ON items(lower(status)) INCLUDE (status) WHERE status <> 'bad'", .{});
    defer index.deinit();
    // Covering a direct dependency of an expression is legal; key identities
    // and included column identities remain separate domains.
    _ = try ddl.apply(a, &schema, index.statement.catalog_ddl);
    var rename = try compiler.compile(a, "ALTER TABLE items RENAME COLUMN status TO state", .{});
    defer rename.deinit();
    const transform = (try ddl.prepareColumnTransform(a, schema, rename.statement.catalog_ddl, .{})).?;
    try std.testing.expectEqualStrings("state", transform.column);
    try std.testing.expect(try ddl.apply(a, &schema, rename.statement.catalog_ddl));
    const props = try @import("schema_columns.zig").properties(schema);
    try std.testing.expect(!props.object.contains("status"));
    try std.testing.expect(props.object.contains("state"));
    const defaults = schema.object.get("column_defaults").?.array.items;
    try std.testing.expectEqualStrings("state", defaults[0].object.get("column").?.string);
    const rendered = try std.json.Stringify.valueAlloc(a, defaults[0], .{});
    try std.testing.expect(std.mem.indexOf(u8, rendered, "status") != null);
    const successor = try std.json.Stringify.valueAlloc(a, schema, .{});
    var compiled = try @import("../schema/mod.zig").PreparedSchemaDefinition.init(backing, successor);
    defer compiled.deinit(backing);
    const saved = try std.json.Stringify.valueAlloc(a, schema, .{});
    try std.testing.expectError(error.UndefinedColumn, ddl.apply(a, &schema, rename.statement.catalog_ddl));
    try std.testing.expectEqualStrings(saved, try std.json.Stringify.valueAlloc(a, schema, .{}));
    var collision = try compiler.compile(a, "ALTER TABLE items RENAME state TO id", .{});
    defer collision.deinit();
    try std.testing.expectError(error.DuplicateSqlColumn, ddl.apply(a, &schema, collision.statement.catalog_ddl));
    try std.testing.expectEqualStrings(saved, try std.json.Stringify.valueAlloc(a, schema, .{}));
    try std.testing.expectError(error.SqlProgramLimitExceeded, ddl.applyWithLimits(a, &schema, blk: {
        var change = rename.statement.catalog_ddl;
        change.schema_change.?.rename_column = .{ .name = "state", .new_name = "status" };
        break :blk change;
    }, .{ .nodes = 1 }));
    try std.testing.expectEqualStrings(saved, try std.json.Stringify.valueAlloc(a, schema, .{}));
}

test "SQL column rename rebinds typed dependencies without changing literals and is allocation atomic" {
    try renameCase(std.testing.allocator);
    try @import("antfly_platform").allocator.checkAllAllocationFailures(std.testing.allocator, renameCase, .{});
}

test "SQL column rename guards separately owned artifact field paths but not labels or schema-derived indexes" {
    const a = std.testing.allocator;
    try requireIndependentIndexes(a, "{\"all\":{\"type\":\"full_text\",\"description\":\"status\"},\"derived\":{\"type\":\"algebraic\",\"fields\":[\"status\"]}}", "status");
    for ([_][]const u8{
        "{\"search\":{\"type\":\"full_text\",\"field\":\"status\"}}",
        "{\"search\":{\"type\":\"full_text\",\"field\":\"status.text\"}}",
        "{\"search\":{\"type\":\"full_text\",\"analysis_config\":{\"field_analyzers\":{\"status\":\"standard\"}}}}",
        "{\"vector\":{\"type\":\"embeddings\",\"sources\":[{\"field\":\"status\"}]}}",
    }) |json| try std.testing.expectError(error.UnsupportedSqlShape, requireIndependentIndexes(a, json, "status"));
    try requireIndependentIndexes(a, "{\"search\":{\"type\":\"full_text\",\"field\":\"status_longer\"}}", "status");
    try requireIndependentIndexes(a, "{\"enrichments\":[],\"resolvers\":{}}", "status");
    try std.testing.expectError(error.UnsupportedSqlShape, requireIndependentIndexes(a, "{\"enrichments\":[{\"name\":\"status\",\"field\":\"body\"}],\"resolvers\":{\"value\":{\"field\":\"body\"}}}", "status"));
    try std.testing.expectError(error.UnsupportedSqlShape, requireIndependentIndexes(a, "{\"enrichments\":[{\"name\":\"embedding\",\"field\":\"status\"}]}", "status"));
    const alias = [_]@import("../storage/db/relational_rewrite_contract.zig").ColumnTransform{.{ .column = "state", .expression_json = "{\"op\":\"column\",\"column\":\"status\"}" }};
    const bindings = @import("schema_ddl.zig").requireTransformIndexBindings;
    try bindings(a, "{}", &alias);
    // Re-evaluating the identical prepared rename against the current record
    // catches an artifact index admitted after the first SQL preparation cut.
    try std.testing.expectError(error.UnsupportedSqlShape, bindings(a, "{\"late\":{\"type\":\"full_text\",\"field\":\"status\"}}", &alias));
}
