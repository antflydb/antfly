"""Generate uslug's Unicode normalization, case folding and category tables.

Run with Python's Unicode 16.0.0 database; output is checked in so runtime
behavior never depends on the host OS or locale.
"""

import unicodedata as u
from pathlib import Path

assert u.unidata_version == "16.0.0", u.unidata_version
mappings, values, classes, compositions, ranges, marks = [], [], [], [], [], []
start = None
for cp in range(0x110000):
    char = chr(cp)
    normalized = u.normalize("NFKD", u.normalize("NFKD", char).casefold())
    if normalized != char and not 0xAC00 <= cp <= 0xD7A3:
        mappings.append((cp, len(values), len(normalized)))
        values.extend(map(ord, normalized))
    if cc := u.combining(char):
        classes.append((cp, cc))
    decomp = u.decomposition(char)
    if decomp and not decomp.startswith("<"):
        parts = list(map(lambda x: int(x, 16), decomp.split()))
        if len(parts) == 2 and u.normalize("NFC", "".join(map(chr, parts))) == char:
            compositions.append(((parts[0] << 21) | parts[1], cp))
    if u.category(char)[0] == "M":
        marks.append((cp, cp))
    allowed = u.category(char)[0] in "LN"
    if allowed and start is None:
        start = cp
    if start is not None and (not allowed or cp == 0x10FFFF):
        ranges.append((start, cp - 1 if not allowed else cp))
        start = None
