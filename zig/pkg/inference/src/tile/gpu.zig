//! GPU lowerings: a tile `RowReduce` rendered as Metal or CUDA source at
//! comptime. Both share one schedule; a `Dialect` supplies the syntax.
//!
//! Schedule per block (one threadgroup / CUDA block):
//! 1. each thread strides over the block, evaluating lets and channel masks
//!    and pushing into per-thread channel state;
//! 2. a SIMD-group (warp) shuffle tree merges lanes;
//! 3. lane 0 of each SIMD-group stages its state in shared memory, and the
//!    first SIMD-group merges those with a second shuffle tree;
//! 4. lane 0 writes the block's `partial_stride` record.

const std = @import("std");
const tile = @import("tile.zig");

const fmt = std.fmt.comptimePrint;

/// Shared-memory slots per channel field: the most SIMD-groups a block can have.
const max_simdgroups = 32;

pub const Dialect = struct {
    name: []const u8,
    preamble: []const u8,
    func: []const u8,
    ref_f32: []const u8,
    ref_u32: []const u8,
    uint: []const u8,
    neg_inf: []const u8,
    exp: []const u8,
    u2f: []const u8,
    f2u: []const u8,
    barrier: []const u8,
    shuffle_f32: []const u8,
    shuffle_u32: []const u8,

    fn shuffle(comptime d: Dialect, comptime which: []const u8, comptime x: []const u8) []const u8 {
        const pattern = if (std.mem.eql(u8, which, "f32")) d.shuffle_f32 else d.shuffle_u32;
        return replace(pattern, "{x}", x);
    }
};

pub const metal: Dialect = .{
    .name = "msl",
    .preamble = "#include <metal_stdlib>\nusing namespace metal;\n",
    .func = "inline",
    .ref_f32 = "thread float &",
    .ref_u32 = "thread uint &",
    .uint = "uint",
    .neg_inf = "(-INFINITY)",
    .exp = "exp",
    .u2f = "as_type<float>",
    .f2u = "as_type<uint>",
    .barrier = "threadgroup_barrier(mem_flags::mem_threadgroup);",
    .shuffle_f32 = "simd_shuffle_down({x}, off)",
    .shuffle_u32 = "simd_shuffle_down({x}, off)",
};

pub const cuda: Dialect = .{
    .name = "cuda",
    .preamble = "",
    .func = "static __device__ __forceinline__",
    .ref_f32 = "float &",
    .ref_u32 = "unsigned int &",
    .uint = "unsigned int",
    .neg_inf = "(__int_as_float(0xff800000))",
    .exp = "expf",
    .u2f = "__uint_as_float",
    .f2u = "__float_as_uint",
    .barrier = "__syncthreads();",
    .shuffle_f32 = "__shfl_down_sync(0xffffffffu, {x}, off)",
    .shuffle_u32 = "__shfl_down_sync(0xffffffffu, {x}, off)",
};

fn replace(comptime s: []const u8, comptime needle: []const u8, comptime with: []const u8) []const u8 {
    comptime {
        var out: []const u8 = "";
        var i: usize = 0;
        while (i < s.len) {
            if (std.mem.startsWith(u8, s[i..], needle)) {
                out = out ++ with;
                i += needle.len;
            } else {
                out = out ++ s[i .. i + 1];
                i += 1;
            }
        }
        return out;
    }
}

