fn generatedNote(comptime k: tile.RowReduce) []const u8 {
    return fmt("// Generated by `zig build tile-kernel-codegen -- --write` from the tile\n" ++
        "// RowReduce `{s}` (src/tile/). Do not edit.\n\n", .{k.name});
}

/// Expression as C-like source; `i` is the element index.
fn expr(comptime k: tile.RowReduce, comptime e: tile.Expr) []const u8 {
    return switch (e) {
        .index => "i",
        .param => |name| paramRef(k, name),
        .lit => |v| fmt("{d}u", .{v}),
        .truth => |t| if (t) "true" else "false",
        .ref => |name| "t_" ++ name,
        .cmp => |c| fmt("({s} {s} {s})", .{ expr(k, c.a.*), c.op.symbol(), expr(k, c.b.*) }),
        .all => |xs| join(k, xs, " && ", "true"),
        .any => |xs| join(k, xs, " || ", "false"),
        .not => |x| "(!" ++ expr(k, x.*) ++ ")",
        .nonzero => |x| "(" ++ expr(k, x.*) ++ " != 0u)",
        .pick => |p| fmt("({s} ? {s} : {s})", .{ expr(k, p.cond.*), expr(k, p.then.*), expr(k, p.otherwise.*) }),
        .not_listed => |name| fmt("(!antfly_tile_listed(i, {s}, {s}))", .{ name, paramRef(k, listCountParam(k, name)) }),
    };
}

fn join(comptime k: tile.RowReduce, comptime xs: []const tile.Expr, comptime sep: []const u8, comptime empty: []const u8) []const u8 {
    if (xs.len == 0) return empty;
    var out: []const u8 = "(" ++ expr(k, xs[0]);
    for (xs[1..]) |x| out = out ++ sep ++ expr(k, x);
    return out ++ ")";
}

fn paramRef(comptime k: tile.RowReduce, comptime name: []const u8) []const u8 {
    const p = k.params[k.paramIndex(name)];
    return if (p.override != null) "t_" ++ name else "p." ++ name;
}

fn listCountParam(comptime k: tile.RowReduce, comptime name: []const u8) []const u8 {
    for (k.bindings) |b| switch (b) {
        .i32_list => |l| if (std.mem.eql(u8, l.name, name)) return l.count,
        else => {},
    };
    unreachable;
}

fn bindingName(comptime k: tile.RowReduce, comptime tag: std.meta.Tag(tile.Binding)) []const u8 {
    for (k.bindings) |b| if (b == tag) return switch (b) {
        .values, .partials, .u32_words => |n| n,
        .i32_list => |l| l.name,
        .params => "p",
    };
    @compileError(k.name ++ ": missing binding " ++ @tagName(tag));
}

fn paramsStruct(comptime k: tile.RowReduce, comptime d: Dialect) []const u8 {
    var out: []const u8 = "struct " ++ k.params_type ++ " {";
    for (k.params) |p| out = out ++ " " ++ d.uint ++ " " ++ p.name ++ ";";
    return out ++ " };\n\n";
}

fn helpers(comptime d: Dialect) []const u8 {
    const u = d.uint;
    return fmt(
        \\{[f]s} bool antfly_tile_listed({[u]s} i, {[list]s}list, {[u]s} count) {{
        \\    for ({[u]s} j = 0u; j < count; ++j) {{
        \\        const int raw = list[j];
        \\        if (raw >= 0 && ({[u]s})raw == i) return true;
        \\    }}
        \\    return false;
        \\}}
        \\{[f]s} void antfly_tile_argmax_push({[rf]s}bv, {[ru]s}bi, float v, {[u]s} i) {{
        \\    if (bi == 0xffffffffu || v > bv || (v == bv && i < bi)) {{ bv = v; bi = i; }}
        \\}}
        \\{[f]s} void antfly_tile_lse_push({[rf]s}m, {[rf]s}s, float v) {{
        \\    if (v == {[ninf]s}) return;
        \\    if (v > m) {{ s = s * {[exp]s}(m - v) + 1.0f; m = v; }} else {{ s += {[exp]s}(v - m); }}
        \\}}
        \\{[f]s} void antfly_tile_lse_merge({[rf]s}m, {[rf]s}s, float m2, float s2) {{
        \\    if (s2 <= 0.0f) return;
        \\    if (s <= 0.0f) {{ m = m2; s = s2; return; }}
        \\    if (m2 > m) {{ s = s * {[exp]s}(m - m2) + s2; m = m2; }} else {{ s += s2 * {[exp]s}(m2 - m); }}
        \\}}
        \\
        \\
    , .{
        .f = d.func,
        .u = u,
        .list = if (std.mem.eql(u8, d.name, "msl")) "device const int *" else "const int *__restrict__ ",
        .rf = d.ref_f32,
        .ru = d.ref_u32,
        .ninf = d.neg_inf,
        .exp = d.exp,
    });
}

fn signature(comptime k: tile.RowReduce, comptime d: Dialect) []const u8 {
    const is_msl = std.mem.eql(u8, d.name, "msl");
    var args: []const []const u8 = &.{};
    for (k.bindings, 0..) |b, binding_slot| {
        const arg = if (is_msl) switch (b) {
            .values => |n| fmt("device const float *{s} [[buffer({d})]]", .{ n, binding_slot }),
            .i32_list => |l| fmt("device const int *{s} [[buffer({d})]]", .{ l.name, binding_slot }),
            .u32_words => |n| fmt("device const uint *{s} [[buffer({d})]]", .{ n, binding_slot }),
            .partials => |n| fmt("device float *{s} [[buffer({d})]]", .{ n, binding_slot }),
            .params => fmt("constant {s} &p [[buffer({d})]]", .{ k.params_type, binding_slot }),
        } else switch (b) {
            .values => |n| "const float *__restrict__ " ++ n,
            .i32_list => |l| "const int *__restrict__ " ++ l.name,
            .u32_words => |n| "const unsigned int *__restrict__ " ++ n,
            .partials => |n| "float *__restrict__ " ++ n,
            .params => "const " ++ k.params_type ++ " p",
        };
        args = args ++ .{arg};
    }
    if (is_msl) args = args ++ .{
        "threadgroup float *sh [[threadgroup(0)]]",
        "uint tid [[thread_index_in_threadgroup]]",
        "uint tg_size [[threads_per_threadgroup]]",
        "uint lane [[thread_index_in_simdgroup]]",
        "uint sg [[simdgroup_index_in_threadgroup]]",
        "uint sg_count [[simdgroups_per_threadgroup]]",
        "uint sg_width [[threads_per_simdgroup]]",
        "uint block [[threadgroup_position_in_grid]]",
    };
    var out: []const u8 = if (is_msl)
        "kernel void " ++ k.name ++ "("
    else
        fmt("extern \"C\" __global__ void __launch_bounds__({d}) {s}(", .{ k.threads, k.name });
    for (args, 0..) |a, i| out = out ++ (if (i == 0) "" else ", ") ++ a;
    out = out ++ ") {\n";
    if (!is_msl) out = out ++ fmt(
        \\    __shared__ float sh[{d}];
        \\    const unsigned int tid = threadIdx.x;
        \\    const unsigned int tg_size = blockDim.x;
        \\    const unsigned int sg_width = 32u;
        \\    const unsigned int lane = tid & 31u;
        \\    const unsigned int sg = tid >> 5u;
        \\    const unsigned int sg_count = (tg_size + 31u) >> 5u;
        \\    const unsigned int block = blockIdx.x;
        \\
    , .{2 * k.channels.len * max_simdgroups});
    return out;
}

fn stateName(comptime ci: usize, comptime field: []const u8) []const u8 {
    return fmt("c{d}_{s}", .{ ci, field });
}

/// Declare or reset channel state to the identity.
fn identity(comptime k: tile.RowReduce, comptime d: Dialect, comptime declare: bool, comptime indent: []const u8) []const u8 {
    var out: []const u8 = "";
    for (k.channels, 0..) |c, ci| {
        const ft = if (declare) "float " else "";
        const ut = if (declare) d.uint ++ " " else "";
        out = out ++ switch (c.reduce) {
            .argmax => fmt("{s}{s}{s} = {s}; {s}{s} = 0xffffffffu; // {s}\n", .{ indent, ft, stateName(ci, "a"), d.neg_inf, ut, stateName(ci, "i"), c.name }),
            .logsumexp => fmt("{s}{s}{s} = {s}; {s}{s} = 0.0f; // {s}\n", .{ indent, ft, stateName(ci, "a"), d.neg_inf, ft, stateName(ci, "b"), c.name }),
        };
    }
    return out;
}

fn shuffleTree(comptime k: tile.RowReduce, comptime d: Dialect, comptime indent: []const u8) []const u8 {
    var out: []const u8 = indent ++ "for (" ++ d.uint ++ " off = sg_width >> 1u; off > 0u; off >>= 1u) {\n";
    for (k.channels, 0..) |c, ci| {
        const a = stateName(ci, "a");
        out = out ++ switch (c.reduce) {
            .argmax => blk: {
                const i = stateName(ci, "i");
                break :blk fmt("{s}    {{ const float oa = {s}; const {s} oi = {s}; if (oi != 0xffffffffu) antfly_tile_argmax_push({s}, {s}, oa, oi); }}\n", .{ indent, d.shuffle("f32", a), d.uint, d.shuffle("u32", i), a, i });
            },
            .logsumexp => blk: {
                const b = stateName(ci, "b");
                break :blk fmt("{s}    {{ const float om = {s}; const float os = {s}; antfly_tile_lse_merge({s}, {s}, om, os); }}\n", .{ indent, d.shuffle("f32", a), d.shuffle("f32", b), a, b });
            },
        };
    }
    return out ++ indent ++ "}\n";
}

fn slot(comptime ci: usize, comptime field: usize, comptime at: []const u8) []const u8 {
    return fmt("sh[{d}u + {s}]", .{ (2 * ci + field) * max_simdgroups, at });
}

pub fn renderPartials(comptime k: tile.RowReduce, comptime d: Dialect) []const u8 {
    comptime {
        @setEvalBranchQuota(200_000);
        k.validate();
        if (k.threads > 1024) @compileError(k.name ++ ": at most 1024 threads per block");
        const u = d.uint;
        var out: []const u8 = license_header ++ generatedNote(k) ++ d.preamble ++ "\n" ++ paramsStruct(k, d) ++ helpers(d) ++ signature(k, d);

        // Params that device state can override.
        for (k.params) |p| if (p.override) |o| {
            out = out ++ fmt("    {s} t_{s} = p.{s};\n", .{ u, p.name, p.name });
            out = out ++ fmt("    if ((p.{s} & {d}u) != 0u) t_{s} = {s}[{d}];\n", .{ o.flag, o.mask, p.name, o.buffer, o.word });
        };
        out = out ++ fmt(
            \\    const {[u]s} start = block * {[block]d}u;
            \\    const {[u]s} end = (start + {[block]d}u < p.{[extent]s}) ? start + {[block]d}u : p.{[extent]s};
            \\
        , .{ .u = u, .block = k.block, .extent = k.extent });
        out = out ++ identity(k, d, true, "    ");

        // 1. Strided per-thread pass.
        out = out ++ fmt("    for ({s} i = start + tid; i < end; i += tg_size) {{\n", .{u});
        out = out ++ fmt("        const float v = {s}[i];\n", .{bindingName(k, .values)});
        for (k.lets) |l| out = out ++ fmt("        const bool t_{s} = {s};\n", .{ l.name, expr(k, l.expr) });
        for (k.channels, 0..) |c, ci| {
            const a = stateName(ci, "a");
            const cond = expr(k, c.where);
            const guard = if (std.mem.eql(u8, cond, "true")) "" else "if (" ++ cond ++ ") ";
            out = out ++ switch (c.reduce) {
                .argmax => fmt("        {s}antfly_tile_argmax_push({s}, {s}, v, i);\n", .{ guard, a, stateName(ci, "i") }),
                .logsumexp => fmt("        {s}antfly_tile_lse_push({s}, {s}, v);\n", .{ guard, a, stateName(ci, "b") }),
            };
        }
        out = out ++ "    }\n";

        // 2. SIMD-group tree.
        out = out ++ shuffleTree(k, d, "    ");

        // 3. Stage per-SIMD-group results, merge in the first SIMD-group.
        out = out ++ "    if (lane == 0u) {\n";
        for (k.channels, 0..) |c, ci| {
            const second = switch (c.reduce) {
                .argmax => fmt("{s}({s})", .{ d.u2f, stateName(ci, "i") }),
                .logsumexp => stateName(ci, "b"),
            };
            out = out ++ fmt("        {s} = {s}; {s} = {s};\n", .{ slot(ci, 0, "sg"), stateName(ci, "a"), slot(ci, 1, "sg"), second });
        }
        out = out ++ "    }\n    " ++ d.barrier ++ "\n";
        out = out ++ "    if (sg != 0u) return;\n";
        out = out ++ "    if (lane < sg_count) {\n";
        for (k.channels, 0..) |c, ci| {
            out = out ++ switch (c.reduce) {
                .argmax => fmt("        {s} = {s}; {s} = {s}({s});\n", .{ stateName(ci, "a"), slot(ci, 0, "lane"), stateName(ci, "i"), d.f2u, slot(ci, 1, "lane") }),
                .logsumexp => fmt("        {s} = {s}; {s} = {s};\n", .{ stateName(ci, "a"), slot(ci, 0, "lane"), stateName(ci, "b"), slot(ci, 1, "lane") }),
            };
        }
        out = out ++ "    } else {\n" ++ identity(k, d, false, "        ") ++ "    }\n";
        out = out ++ shuffleTree(k, d, "    ");

        // 4. Write the record.
        const partials = bindingName(k, .partials);
        out = out ++ "    if (lane != 0u) return;\n";
        out = out ++ fmt("    const {s} q = block * {d}u;\n", .{ u, k.partial_stride });
        for (k.channels, 0..) |c, ci| {
            const second = switch (c.reduce) {
                .argmax => fmt("{s}({s})", .{ d.u2f, stateName(ci, "i") }),
                .logsumexp => stateName(ci, "b"),
            };
            out = out ++ fmt("    {s}[q + {d}u] = {s}; {s}[q + {d}u] = {s};\n", .{ partials, 2 * ci, stateName(ci, "a"), partials, 2 * ci + 1, second });
        }
        for (2 * k.channels.len..k.partial_stride) |pad| out = out ++ fmt("    {s}[q + {d}u] = 0.0f;\n", .{ partials, pad });
        return out ++ "}\n";
    }
}

/// CUDA only: merge partial records into one record (single thread). Metal
/// keeps the hand-written Whisper reduce, which also picks the token.
pub fn renderCudaCombine(comptime k: tile.RowReduce) []const u8 {
    comptime {
        @setEvalBranchQuota(100_000);
        const d = cuda;
        var out: []const u8 = fmt("\nextern \"C\" __global__ void {s}_combine(const float *__restrict__ partials, float *__restrict__ out, const unsigned int partial_count) {{\n", .{k.name});
        out = out ++ "    if (blockIdx.x != 0u || threadIdx.x != 0u) return;\n";
        out = out ++ identity(k, d, true, "    ");
        out = out ++ "    for (unsigned int r = 0u; r < partial_count; ++r) {\n";
        out = out ++ fmt("        const float *q = partials + r * {d}u;\n", .{k.partial_stride});
        for (k.channels, 0..) |c, ci| {
            out = out ++ switch (c.reduce) {
                .argmax => fmt("        {{ const unsigned int oi = __float_as_uint(q[{d}]); if (oi != 0xffffffffu) antfly_tile_argmax_push({s}, {s}, q[{d}], oi); }}\n", .{ 2 * ci + 1, stateName(ci, "a"), stateName(ci, "i"), 2 * ci }),
                .logsumexp => fmt("        antfly_tile_lse_merge({s}, {s}, q[{d}], q[{d}]);\n", .{ stateName(ci, "a"), stateName(ci, "b"), 2 * ci, 2 * ci + 1 }),
            };
        }
        out = out ++ "    }\n";
        for (k.channels, 0..) |c, ci| {
            const second = switch (c.reduce) {
                .argmax => fmt("__uint_as_float({s})", .{stateName(ci, "i")}),
                .logsumexp => stateName(ci, "b"),
            };
            out = out ++ fmt("    out[{d}] = {s}; out[{d}] = {s};\n", .{ 2 * ci, stateName(ci, "a"), 2 * ci + 1, second });
        }
        for (2 * k.channels.len..k.partial_stride) |pad| out = out ++ fmt("    out[{d}] = 0.0f;\n", .{pad});
        return out ++ "}\n";
    }
}

pub fn renderMetal(comptime k: tile.RowReduce) []const u8 {
    return renderPartials(k, metal);
}

pub fn renderCuda(comptime k: tile.RowReduce) []const u8 {
    return renderPartials(k, cuda) ++ renderCudaCombine(k);
}

/// The Metal source as a C string literal header, for metal_kernels.m to
/// compile into its own library at runtime.
pub fn renderMetalHeader(comptime k: tile.RowReduce, comptime symbol: []const u8) []const u8 {
    comptime {
        @setEvalBranchQuota(2_000_000);
        const src = renderMetal(k);
        var out: []const u8 = license_header ++ generatedNote(k) ++ "static const char " ++ symbol ++ "[] =\n";
        var line_start: usize = 0;
        for (src, 0..) |ch, idx| {
            if (ch != '\n') continue;
            out = out ++ "    \"" ++ escape(src[line_start..idx]) ++ "\\n\"\n";
            line_start = idx + 1;
        }
        return out ++ "    ;\n";
    }
}

fn escape(comptime s: []const u8) []const u8 {
    var out: []const u8 = "";
    for (s) |ch| out = out ++ switch (ch) {
        '\\' => "\\\\",
        '"' => "\\\"",
        else => &[_]u8{ch},
    };
    return out;
}
