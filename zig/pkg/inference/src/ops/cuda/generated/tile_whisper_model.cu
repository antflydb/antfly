extern "C" __global__ void __launch_bounds__(128) antfly_tile_layer_norm(const float *__restrict__ x, const float *__restrict__ gamma, const float *__restrict__ beta, float *out, const antfly_tile_norm_params p) {
    const unsigned int row = blockIdx.x; const unsigned int tid = threadIdx.x;
    const unsigned int lane = tid & 31u; const unsigned int sg = tid >> 5u; const unsigned int sg_count = (blockDim.x + 31u) >> 5u;
    __shared__ float red[32];
    if (row >= p.rows) return;
    const unsigned int base = row * p.dim;
    float s = 0.0f;
    for (unsigned int c = tid; c < p.dim; c += 128u) s += x[base + c];
    float sum = 0.0f;
    {
        const float part = antfly_tile_warp_sum(s);
        if (lane == 0u) red[sg] = part;
        __syncthreads();
        float total = 0.0f;
        for (unsigned int i = 0u; i < sg_count; ++i) total += red[i];
        sum = total;
        __syncthreads();
    }
    const float mean = sum / (float)p.dim;
    float q = 0.0f;
    for (unsigned int c = tid; c < p.dim; c += 128u) { const float d = x[base + c] - mean; q += d * d; }
    float sq = 0.0f;
    {
        const float part = antfly_tile_warp_sum(q);
        if (lane == 0u) red[sg] = part;
        __syncthreads();
        float total = 0.0f;
        for (unsigned int i = 0u; i < sg_count; ++i) total += red[i];
        sq = total;
        __syncthreads();
    }
    const float inv = rsqrtf(sq / (float)p.dim + 1e-5f);
    for (unsigned int c = tid; c < p.dim; c += 128u) out[base + c] = (x[base + c] - mean) * inv * gamma[c] + beta[c];
}

extern "C" __global__ void __launch_bounds__(128) antfly_tile_attention_hd64(const float *__restrict__ q, const float *__restrict__ k, const float *__restrict__ v, float *out, const antfly_tile_attention_params p) {
    const uint3 tg_pos = make_uint3(blockIdx.x, blockIdx.y, 0u);
    const unsigned int lane = threadIdx.x & 31u; const unsigned int sg = threadIdx.x >> 5u;
    // One SIMD-group per (query, head); lane owns elements lane + 32 * t.
    const unsigned int h = tg_pos.y;
    const unsigned int i = tg_pos.x * 4u + sg;
    if (i >= p.tq || h >= p.heads) return;
    float qv[2]; float o[2];
    for (unsigned int t = 0u; t < 2u; ++t) { qv[t] = q[i * p.ld_q + h * 64u + lane + 32u * t] * p.scale; o[t] = 0.0f; }
    const unsigned int limit = (p.causal != 0u && p.q_offset + i + 1u < p.tk) ? p.q_offset + i + 1u : p.tk;
    float m = (__int_as_float(0xff800000)); float l = 0.0f;
    for (unsigned int j = 0u; j < limit; ++j) {
        float part = 0.0f;
        for (unsigned int t = 0u; t < 2u; ++t) part += qv[t] * k[j * p.ld_k + h * 64u + lane + 32u * t];
        const float s = antfly_tile_warp_sum(part);
        const float m_new = fmaxf(m, s);
        const float corr = expf(m - m_new);
        const float pr = expf(s - m_new);
        l = l * corr + pr;
        for (unsigned int t = 0u; t < 2u; ++t) o[t] = o[t] * corr + pr * v[j * p.ld_v + h * 64u + lane + 32u * t];
        m = m_new;
    }
    const float inv = l > 0.0f ? 1.0f / l : 0.0f;
    for (unsigned int t = 0u; t < 2u; ++t) out[i * p.ld_o + h * 64u + lane + 32u * t] = o[t] * inv;
}

