fn pythonPrintable(cp: u21) bool {
    var lo: usize = 0;
    var hi = python_nonprintable.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        const range = python_nonprintable[mid];
        const first: u21 = @intCast(range >> 21);
        const last: u21 = @truncate(range);
        if (cp < first) hi = mid else if (cp > last) lo = mid + 1 else return false;
    }
    return true;
}

