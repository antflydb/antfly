  export ANTFLY_INFERENCE_GEMMA4_MIN_GENERATED_TOKENS="${ANTFLY_INFERENCE_GEMMA4_MIN_GENERATED_TOKENS:-${ANTFLY_INFERENCE_GEMMA4_BENCH_MAX_TOKENS:-128}}"
