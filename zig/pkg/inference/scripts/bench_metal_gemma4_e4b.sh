    export ANTFLY_INFERENCE_GEMMA4_MIN_PREFILL_FRAME_EXECUTE="${ANTFLY_INFERENCE_GEMMA4_MIN_PREFILL_FRAME_EXECUTE:-1}"
    export ANTFLY_INFERENCE_GEMMA4_REQUIRE_MTP_ENABLED="${ANTFLY_INFERENCE_GEMMA4_REQUIRE_MTP_ENABLED:-1}"
    export ANTFLY_INFERENCE_GEMMA4_MIN_SPECULATIVE_ROUNDS="${ANTFLY_INFERENCE_GEMMA4_MIN_SPECULATIVE_ROUNDS:-1}"
    export ANTFLY_INFERENCE_GEMMA4_MIN_SPECULATIVE_DRAFTED="${ANTFLY_INFERENCE_GEMMA4_MIN_SPECULATIVE_DRAFTED:-1}"
