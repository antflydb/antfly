set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

env_flag_enabled() {
  case "${1:-}" in
    ""|0|false|FALSE|no|NO|off|OFF) return 1 ;;
    *) return 0 ;;
  esac
}

q4_0_f16_ffn_flag_value() {
  if [[ -n "${TERMITE_METAL_Q4_0_F16_FFN_EXPERIMENT+x}" ]]; then
    printf '%s\n' "$TERMITE_METAL_Q4_0_F16_FFN_EXPERIMENT"
  else
    printf '%s\n' "${TERMITE_METAL_ENABLE_Q4_0_F16_FFN:-0}"
  fi
}

q4_0_sumsq_flag_value() {
  if env_flag_enabled "${TERMITE_METAL_DISABLE_Q4_0_LINEAR_RMS_ADD_SUMSQ:-0}"; then
    printf '0\n'
  elif [[ -n "${TERMITE_METAL_ENABLE_Q4_0_LINEAR_RMS_ADD_SUMSQ+x}" ]]; then
    printf '%s\n' "$TERMITE_METAL_ENABLE_Q4_0_LINEAR_RMS_ADD_SUMSQ"
  else
    printf '%s\n' "${TERMITE_METAL_Q4_0_LINEAR_RMS_ADD_SUMSQ_EXPERIMENT:-0}"
  fi
}

q4_0_f16_project_flag_value() {
  if [[ -n "${TERMITE_METAL_Q4_0_LINEAR_RMS_ADD_F16_PROJECT_EXPERIMENT+x}" ]]; then
    printf '%s\n' "$TERMITE_METAL_Q4_0_LINEAR_RMS_ADD_F16_PROJECT_EXPERIMENT"
  else
    printf '%s\n' "${TERMITE_METAL_Q4_0_LINEAR_RMS_ADD_F16_PROJECT:-0}"
  fi
}

if env_flag_enabled "${ANTFLY_INFERENCE_GEMMA4_BENCH_LOCK:-1}"; then
  BENCH_LOCK_DIR="${ANTFLY_INFERENCE_GEMMA4_BENCH_LOCK_DIR:-/tmp/antfly-gemma4-e4b-metal-bench.lock}"
  cleanup_bench_lock() {
    rm -f "$BENCH_LOCK_DIR/pid"
    rmdir "$BENCH_LOCK_DIR" 2>/dev/null || true
  }
  if mkdir "$BENCH_LOCK_DIR" 2>/dev/null; then
    printf '%s\n' "$$" >"$BENCH_LOCK_DIR/pid"
    trap cleanup_bench_lock EXIT
    trap 'cleanup_bench_lock; exit 130' INT
    trap 'cleanup_bench_lock; exit 143' TERM HUP
  else
    echo "another Gemma4 E4B Metal bench is running; set ANTFLY_INFERENCE_GEMMA4_BENCH_LOCK=0 to override" >&2
    exit 75
  fi
fi

