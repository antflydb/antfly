#!/usr/bin/env python3
"""Generate Unicode15 Python re.IGNORECASE literal equivalence and fixtures."""
from __future__ import annotations
import argparse
import re
import _sre
from pathlib import Path
from re._casefix import _EXTRA_CASES
from oracle import prepare_runtime, write_json


def generate(source: Path, output: Path) -> None:
    provenance, _ = prepare_runtime(source)
    parents: dict[int, int] = {}

    def root(cp: int) -> int:
        parent = parents.get(cp, cp)
        if parent != cp:
            parent = root(parent)
            parents[cp] = parent
        return parent

    def join(left: int, right: int) -> None:
        left, right = root(left), root(right)
        if left != right:
            parents[max(left, right)] = min(left, right)

    for cp in range(0x110000):
        lowered = _sre.unicode_tolower(cp)
        if cp != lowered:
            join(cp, lowered)
        for extra in _EXTRA_CASES.get(lowered, ()):
            join(cp, extra)
    rows = [(cp, root(cp)) for cp in sorted(parents) if root(cp) != cp]
    target = output / "gliner_boundary_case_data.zig"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        "// Generated by generate_case_equivalence.py; Python 3.12.3 Unicode 15.0.0.\n"
        "// Python re._casefix and _sre.unicode_tolower define literal IGNORECASE.\n"
        "pub const Pair = struct { cp: u21, representative: u21 };\n"
        "pub const pairs = [_]Pair{\n" +
        "".join(f"    .{{ .cp = 0x{cp:X}, .representative = 0x{rep:X} }},\n" for cp, rep in rows) +
        "};\n", encoding="utf-8")
    cases = []
    for text, choices in [
        ("İpek ıpek IPEK ipek", ["ipek"]),
        ("ſale sale SALE pre-sale sales", ["sale"]),
        ("Σ σ ς Σς", ["σ"]),
        ("Straße STRASSE straße", ["strasse", "straße"]),
        ("K K k Kelvin", ["k"]),
        ("(positive) negative_positive positive!", ["positive", "negative"]),
        ("東京 東京駅 東京都", ["東京"]),
        ("a.b aXb a.b.c", ["a.b"]),
        ("é é É", ["é", "é"]),
        ("🙂positive🙂 neutral\nnegative", ["positive", "neutral", "negative"]),
        ("books books\ttoys TOYS", ["books", "toys"]),
        ("𐐀 𐐨", ["𐐨"]),
    ]:
        expected = []
        for index, choice in enumerate(choices):
            for match in re.finditer(rf"(?<!\w){re.escape(choice)}(?!\w)", text, flags=re.IGNORECASE):
                expected.append({"choice": index, "start": len(text[:match.start()].encode()), "end": len(text[:match.end()].encode())})
        expected.sort(key=lambda m: m["start"])
        cases.append({"text": text, "choices": choices, "matches": expected})
    write_json(output / "case_equivalence.json", {"format_version": 1, "provenance": provenance, "pairs": len(rows), "cases": cases})


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    generate(args.upstream, args.output)
