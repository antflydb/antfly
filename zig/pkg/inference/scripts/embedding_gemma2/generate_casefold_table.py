#!/usr/bin/env python3
"""Generate EmbeddingGemma2's pinned Python 3.11 / Unicode 14 casefold table."""

from __future__ import annotations

import argparse
import hashlib
import sys
import unicodedata
from pathlib import Path

repository_root = next(parent for parent in Path(__file__).resolve().parents
                       if (parent / "scripts/generated_source_licenses.py").is_file())
sys.path.insert(0, str(repository_root / "scripts"))
from generated_source_licenses import unicode_source_header

OUTPUT = Path(__file__).resolve().parents[2] / "src/finetune/embedding_gemma2_casefold_data.zig"
SHARED = Path(__file__).resolve().parents[2] / "src/pipelines/extraction_casefold_data.zig"
PYTHON_PROFILE = (3, 11)
UNICODE_VERSION = "14.0.0"


def render() -> str:
    if sys.version_info[:2] != PYTHON_PROFILE or unicodedata.unidata_version != UNICODE_VERSION:
        raise SystemExit(f"expected Python {PYTHON_PROFILE[0]}.{PYTHON_PROFILE[1]} / Unicode {UNICODE_VERSION}, "
                         f"got Python {sys.version_info.major}.{sys.version_info.minor} / Unicode {unicodedata.unidata_version}")
    entries = []
    identity = hashlib.sha256()
    for codepoint in range(0x110000):
        source = chr(codepoint)
        folded = source.casefold()
        if folded == source:
            continue
        target = [ord(char) for char in folded]
        if len(target) > 3:
            raise RuntimeError(f"casefold expansion exceeds table width at U+{codepoint:04X}")
        padded = target + [0] * (3 - len(target))
        entries.append(f"    .{{ .source = 0x{codepoint:x}, .target = .{{ "
                       + ", ".join(f"0x{value:x}" for value in padded)
                       + f" }}, .len = {len(target)} }},")
        identity.update(codepoint.to_bytes(4, "big"))
        identity.update(bytes([len(target)]))
        for value in target:
            identity.update(value.to_bytes(4, "big"))
    expected_shared = "pub const entries = [_]Entry{\n" + "\n".join(entries) + "\n};\n"
    shared = SHARED.read_text()
    if shared[shared.index("pub const entries"): ] != expected_shared:
        raise SystemExit("shared extraction casefold mappings differ from pinned Python 3.11")
    lines = [
        "// Generated by scripts/embedding_gemma2/generate_casefold_table.py; do not edit.",
        "// The shared table is byte-for-byte equal to pinned CPython 3.11 mappings.",
        'const shared = @import("../pipelines/extraction_casefold_data.zig");',
        'pub const python_version = "3.11";',
        'pub const unicode_version = "14.0.0";',
        'pub const normalization_profile = "python-3.11-unicode-14.0.0-casefold-split-join/v1";',
        f'pub const mapping_sha256 = "{identity.hexdigest()}";',
        "pub const entries = shared.entries;",
        "",
    ]
    return unicode_source_header(__file__) + "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.write:
        OUTPUT.write_text(generated)
        return 0
    if not OUTPUT.is_file() or OUTPUT.read_text() != generated:
        print("stale EmbeddingGemma2 casefold table; regenerate with --write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
