"""Check the official training RoPE's reference-initialized FP32 constants."""

from __future__ import annotations

import argparse
from pathlib import Path


SOURCE_AXIAL_COMMENT = "\n// Source axial inverse frequencies: original Gemma4VisionRotaryEmbedding,\n// Transformers5.19 source edc123ab83fbb25548ec65536eaecee998c088653adf683be3ef69d62e2bfea9,\n// original pinned config b8f1e9931b57fbc054acdb445c41765d55b0074c58d145fa82839941ad1b5bb3.\n// Captured on CPU Torch2.14.1; original default-F32 constructor bits also\n// match pinned Torch2.13.0+cu130, including the actual BF16-loaded model's\n// F32 vision inv_freq buffer. Device trigonometric receiving remains pending.\n"


def render(model: Path) -> str:
    import torch
    from transformers import EmbeddingGemma2Config
    from transformers.models.embedding_gemma2.modeling_embedding_gemma2 import (
        EmbeddingGemma2RotaryEmbedding,
    )

    whole_config = EmbeddingGemma2Config.from_pretrained(model, local_files_only=True)
    config = whole_config.text_config
    rotary = EmbeddingGemma2RotaryEmbedding(config, device="cpu")
    result = [
        "// Copyright 2026 Antfly, Inc.",
        "// SPDX-License-Identifier: Apache-2.0",
        "#pragma once",
        "",
        "// Generated by scripts/embedding_gemma2/generate_training_rope_frequencies.py.",
        "// The official model initializes inv_freq on the CPU in FP32, then copies",
        "// it to CUDA. Recomputing powf on the device changes BF16 rotary coefficients",
        "// at rounding boundaries. Keep those initialization bits in both training",
        "// directions; training and serving share these official frequency values.",
        "// Reference: Transformers a96730c8c97b8efbf35bbaf7f5da33ec99231a49,",
        "// Torch 2.14.0+cu130, default RoPE, official google/embeddinggemma-2 config.",
        "",
    ]
    for kind, head_dim, theta in (
        ("sliding_attention", 256, 10000.0),
        ("full_attention", 512, 1000000.0),
    ):
        params = config.rope_parameters[kind]
        layer_config = config.per_layer_config[kind]
        if (
            params["rope_type"] != "default"
            or params["rope_theta"] != theta
            or layer_config.head_dim != head_dim
        ):
            raise ValueError(f"unsupported official RoPE configuration: {kind}")
        frequencies = getattr(rotary, f"{kind}_inv_freq")
        if frequencies.dtype != torch.float32 or frequencies.numel() != head_dim // 2:
            raise ValueError(f"invalid reference frequency shape: {kind}")
        bits = frequencies.view(torch.int32).tolist()
        name = "sliding" if head_dim == 256 else "full"
        result.append(
            f"static __device__ __constant__ unsigned int eg2_training_rope_{name}_bits[{len(bits)}] = {{"
        )
        for offset in range(0, len(bits), 8):
            result.append(
                "    "
                + ", ".join(f"0x{value:08x}u" for value in bits[offset : offset + 8])
                + ","
            )
        result.extend(["};", ""])
    result.extend(
        [
            "__device__ __forceinline__ float eg2_training_rope_inverse_frequency(",
            "    float theta, unsigned int dim, unsigned int pair) {",
            "    if (dim == 256u && theta == 10000.0f)",
            "        return __uint_as_float(eg2_training_rope_sliding_bits[pair]);",
            "    if (dim == 512u && theta == 1000000.0f)",
            "        return __uint_as_float(eg2_training_rope_full_bits[pair]);",
            "    return __fdiv_rn(1.0f, powf(theta, (2.0f * pair) / (float)dim));",
            "}",
            "",
        ]
    )
    from transformers.models.gemma4.modeling_gemma4 import Gemma4VisionRotaryEmbedding
    vision = whole_config.vision_config
    if vision.head_dim != 64 or vision.rope_parameters != {"rope_theta": 100.0, "rope_type": "axial"}:
        raise ValueError("unsupported source axial frequency geometry")
    axial, factor = Gemma4VisionRotaryEmbedding.compute_axial_rope_parameters(vision, device="cpu")
    if axial.dtype != torch.float32 or axial.numel() != 16 or factor != 1.0:
        raise ValueError("invalid source axial frequency metadata")
    # Original local capture used Torch2.14.1; validation on another version
    # MUST compare actual original-function bits, never substitute generic pow.
    result.extend(SOURCE_AXIAL_COMMENT.lstrip("\n").splitlines())
    result.append("static __device__ __constant__ unsigned int antfly_rotary_axis32_theta100_bits[16] = {")
    axial_bits = axial.view(torch.int32).tolist()
    for offset in range(0, 16, 8):
        result.append("    " + ", ".join(f"0x{value:08x}u" for value in axial_bits[offset:offset+8]) + ",")
    result.extend(["};", ""])
    return "\n".join(result)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, required=True)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[2]
        / "src/ops/cuda/kernels/rotary_frequency_training.cuh",
    )
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    expected = render(args.model)
    if args.write:
        args.output.write_text(expected)
    elif args.output.read_text() != expected:
        raise SystemExit(
            "training RoPE constants differ from the pinned reference initialization"
        )
    print("official RoPE: 384 training and 16 source axial FP32 frequencies verified")


if __name__ == "__main__":
    main()
