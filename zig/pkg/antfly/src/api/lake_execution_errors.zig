const names = blk: {
    var result: [values.len][]const u8 = undefined;
    for (values, 0..) |value, i| result[i] = @errorName(value);
    break :blk result;
};
pub fn fromName(name: []const u8) anyerror {
    var low: usize = 0;
    var high: usize = names.len;
    while (low < high) {
        const middle = low + (high - low) / 2;
        switch (std.mem.order(u8, name, names[middle])) {
            .eq => return values[middle],
            .lt => high = middle,
            .gt => low = middle + 1,
        }
    }
    return @import("engine_errors").fromName(name);
}
test "external lake execution preserves every operation-owned error name" {
    for (names, values) |name, value| try std.testing.expectEqual(value, fromName(name));
    try std.testing.expectEqual(error.FileNotFound, fromName("FileNotFound"));
    try std.testing.expectEqual(error.RuntimeBoundaryFailure, fromName("_unknown_lake_operation_error_"));
}
