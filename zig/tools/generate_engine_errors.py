"""Generate compiler-local names for lossless private inference error transport."""

import argparse
import ast
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def error_names(source):
    # Strip strings/comments before finding literal errors and declared sets.
    text = re.sub(r'//[^\n]*|"(?:\\.|[^"\\])*"', " ", source)
    names = set(re.findall(r"\berror\.([A-Za-z_][A-Za-z_0-9]*)", text))
    for body in re.findall(r"\berror\s*\{([^}]+)\}", text):
        names.update(
            word.strip() for word in body.split(",") if word.strip().isidentifier()
        )
    return names


def contents(zig):
    environment = subprocess.check_output([zig, "env"], text=True)
    match = re.search(r'\.std_dir\s*=\s*("(?:\\.|[^"\\])*"),', environment)
    if match is None:
        raise RuntimeError("could not locate the compiler standard library")
    std = Path(ast.literal_eval(match[1]))
    roots = [
        ROOT / "pkg/inference/src",
        ROOT / "lib",
        ROOT / "pkg/antfly-embedded/src",
        std,
    ]
    names = set()
    for root in roots:
        for source in root.rglob("*.zig"):
            names.update(error_names(source.read_text()))
    header = (
        (ROOT / "lib/runtime/src/runtime_error_abi.zig").read_text().split("//!")[0]
    )
    lines = [
        header,
        "//! Generated by tools/generate_engine_errors.py with the pinned compiler.\n",
        "//! Only names cross the private boundary; integer error codes stay local.\n",
        'const std = @import("std");\nconst names = blk: {\n',
        "    @setEvalBranchQuota(2_000_000);\n",
        "    break :blk std.StaticStringMap(anyerror).initComptime(.{\n",
    ]
    for name in sorted(names):
        literal = json.dumps(name)
        lines.append(f"        .{{ {literal}, error.@{literal} }},\n")
    lines += [
        "    });\n};\n",
        "pub fn fromName(name: []const u8) anyerror {\n",
        "    return names.get(name) orelse error.RuntimeBoundaryFailure;\n}\n",
    ]
    return subprocess.check_output(
        [zig, "fmt", "--stdin"], input="".join(lines), text=True
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--zig", default="zig")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "pkg/inference/src/host/engine_errors.zig"
    generated = contents(args.zig)
    if args.check:
        if output.read_text() != generated:
            raise SystemExit(
                "inference engine error names are stale; regenerate with the pinned Zig compiler"
            )
    else:
        output.write_text(generated)


if __name__ == "__main__":
    main()
