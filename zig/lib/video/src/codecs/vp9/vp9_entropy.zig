pub const vpx_prob = common.vpx_prob;
pub fn get_prob(arg_num: c_uint, arg_den: c_uint) callconv(.c) vpx_prob {
    var num = arg_num;
    _ = &num;
    var den = arg_den;
    _ = &den;
    if (antfly_codec_afz_vp9_failed() != 0) {
        return 0;
    }
    _ = @as(c_int, 0);
    if (antfly_codec_afz_vp9_failed() != 0) {
        return 0;
    }
    {
        if (antfly_codec_afz_vp9_failed() != 0) {
            return 0;
        }
        const p: c_int = @bitCast(@as(c_uint, @truncate(((@as(u64, num) *% @as(u64, 256)) +% @as(u64, den >> @intCast(@as(c_uint, 1)))) / @as(u64, den))));
        _ = &p;
        if (antfly_codec_afz_vp9_failed() != 0) {
            return 0;
        }
        const clipped_prob: c_int = (p | ((@as(c_int, 255) - p) >> @intCast(@as(c_int, 23)))) | @as(c_int, @intFromBool(p == @as(c_int, 0)));
        _ = &clipped_prob;
        if (antfly_codec_afz_vp9_failed() != 0) {
            return 0;
        }
        return @bitCast(@as(i8, @truncate(clipped_prob)));
    }
}
pub fn get_binary_prob(arg_n0: c_uint, arg_n1: c_uint) callconv(.c) vpx_prob {
    var n0 = arg_n0;
    _ = &n0;
    var n1 = arg_n1;
    _ = &n1;
    if (antfly_codec_afz_vp9_failed() != 0) {
        return 0;
    }
    const den: c_uint = n0 +% n1;
    _ = &den;
    if (antfly_codec_afz_vp9_failed() != 0) {
        return 0;
    }
    if (den == @as(c_uint, 0)) {
        if (antfly_codec_afz_vp9_failed() != 0) {
            return 0;
        }
        return 128;
    }
    return get_prob(n0, den);
}
pub fn weighted_prob(arg_prob1: c_int, arg_prob2: c_int, arg_factor: c_int) callconv(.c) vpx_prob {
    var prob1 = arg_prob1;
    _ = &prob1;
    var prob2 = arg_prob2;
    _ = &prob2;
    var factor = arg_factor;
    _ = &factor;
    if (antfly_codec_afz_vp9_failed() != 0) {
        return 0;
    }
    return @bitCast(@as(i8, @truncate((((prob1 * (@as(c_int, 256) - factor)) + (prob2 * factor)) + (@as(c_int, 1) << @intCast(@as(c_int, 8) - @as(c_int, 1)))) >> @intCast(@as(c_int, 8)))));
}
pub fn merge_probs(arg_pre_prob: vpx_prob, arg_ct: [*c]const c_uint, arg_count_sat: c_uint, arg_max_update_factor: c_uint) callconv(.c) vpx_prob {
    var pre_prob = arg_pre_prob;
    _ = &pre_prob;
    var ct = arg_ct;
    _ = &ct;
    var count_sat = arg_count_sat;
    _ = &count_sat;
    var max_update_factor = arg_max_update_factor;
    _ = &max_update_factor;
    if (antfly_codec_afz_vp9_failed() != 0) {
        return 0;
    }
    const prob: vpx_prob = get_binary_prob(ct[@as(c_int, 0)], ct[@as(c_int, 1)]);
    _ = &prob;
    if (antfly_codec_afz_vp9_failed() != 0) {
        return 0;
    }
    const count: c_uint = if ((ct[@as(c_int, 0)] +% ct[@as(c_int, 1)]) < count_sat) ct[@as(c_int, 0)] +% ct[@as(c_int, 1)] else count_sat;
    _ = &count;
    if (antfly_codec_afz_vp9_failed() != 0) {
        return 0;
    }
    const factor: c_uint = (max_update_factor *% count) / count_sat;
    _ = &factor;
    if (antfly_codec_afz_vp9_failed() != 0) {
        return 0;
    }
    return weighted_prob(pre_prob, prob, @bitCast(@as(c_uint, @truncate(factor))));
}
