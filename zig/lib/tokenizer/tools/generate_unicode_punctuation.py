"""Generate a compact Unicode punctuation bitmap for the BERT pre-tokenizer.

Derives the exact classifications used by tokenizers==0.22.1.

Usage:
  generate_unicode_punctuation.py OUTPUT
"""

from __future__ import annotations
import pathlib
import sys
import tokenizers
from tokenizers.pre_tokenizers import BertPreTokenizer

repository_root = next(
    parent
    for parent in pathlib.Path(__file__).resolve().parents
    if (parent / "scripts/generated_source_licenses.py").is_file()
)
sys.path.insert(0, str(repository_root / "scripts"))
from generated_source_licenses import unicode_source_header

reference = BertPreTokenizer()

REFERENCE_VERSION = "0.22.1"
CODEPOINT_COUNT = 0x110000
PAGE_CODEPOINTS = 256
PAGE_BYTES = PAGE_CODEPOINTS // 8  # 1 bit per codepoint


def is_punctuation(cp: int) -> bool:
    if 0xD800 <= cp <= 0xDFFF:
        return False
    # Sentinels distinguish isolated punctuation from whitespace and word text.
    splits = reference.pre_tokenize_str("a" + chr(cp) + "b")
    return len(splits) == 3 and splits[1][0] == chr(cp)


def packed_pages(bits: bytearray) -> tuple[list[int], list[bytes]]:
    indices: list[int] = []
    unique_pages: list[bytes] = []
    page_ids: dict[bytes, int] = {}
    for base in range(0, CODEPOINT_COUNT, PAGE_CODEPOINTS):
        packed = bytearray(PAGE_BYTES)
        for offset in range(PAGE_CODEPOINTS):
            if bits[base + offset]:
                packed[offset >> 3] |= 1 << (offset & 7)
        page = bytes(packed)
        page_id = page_ids.get(page)
        if page_id is None:
            page_id = len(unique_pages)
            if page_id > 255:
                raise ValueError("deduplicated page count no longer fits u8")
            page_ids[page] = page_id
            unique_pages.append(page)
        indices.append(page_id)
    return indices, unique_pages


def format_values(values, width, indent="    "):
    rows = []
    for start in range(0, len(values), width):
        rows.append(
            indent + ", ".join(str(v) for v in values[start : start + width]) + ","
        )
    return "\n".join(rows)


def render(indices, pages) -> str:
    rendered_pages = [
        "    .{\n" + format_values(p, 16, "        ") + "\n    }," for p in pages
    ]
    return f"""// Generated by tools/generate_unicode_punctuation.py from tokenizers {REFERENCE_VERSION}.
// Do not edit by hand.

pub const reference_version = "{REFERENCE_VERSION}";

const page_index = [{len(indices)}]u8{{
{format_values(indices, 32)}
}};

const pages = [{len(pages)}][{PAGE_BYTES}]u8{{
{chr(10).join(rendered_pages)}
}};

/// Exact pinned-reference BERT punctuation classification, including ASCII
/// punctuation whose general category is a symbol rather than P*.
pub inline fn isPunctuation(codepoint: u21) bool {{
    const page = pages[page_index[codepoint >> 8]];
    const byte = page[(codepoint & 0xff) >> 3];
    return (byte >> @intCast(codepoint & 7)) & 1 == 1;
}}
"""


def main() -> None:
    if tokenizers.__version__ != REFERENCE_VERSION:
        raise SystemExit(
            f"expected tokenizers {REFERENCE_VERSION}, got {tokenizers.__version__}"
        )
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    bits = bytearray(CODEPOINT_COUNT)
    for cp in range(CODEPOINT_COUNT):
        bits[cp] = 1 if is_punctuation(cp) else 0
    indices, pages = packed_pages(bits)
    output = pathlib.Path(sys.argv[1])
    output.write_text(
        unicode_source_header(__file__) + render(indices, pages), encoding="utf-8"
    )
    print(f"generated {len(indices)} page indices and {len(pages)} unique pages")


if __name__ == "__main__":
    main()
