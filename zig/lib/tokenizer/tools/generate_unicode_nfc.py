"""Generate generic Unicode 15 NFC plus pinned tokenizers 0.22.1 WordPiece data.

uv run --python 3.12 --with tokenizers==0.22.1 python tools/generate_unicode_nfc.py
"""

import hashlib
import sys
import unicodedata as ud
import tokenizers
from tokenizers import normalizers as hf

if tokenizers.__version__ != "0.22.1":
    raise SystemExit("expected tokenizers 0.22.1")
reference_lower = hf.Lowercase()
reference_marks = hf.StripAccents()
reference_bert_marks = hf.BertNormalizer(
    lowercase=False, strip_accents=True, clean_text=False, handle_chinese_chars=False
)
reference_clean = hf.BertNormalizer(
    lowercase=False, strip_accents=False, handle_chinese_chars=False
)
reference_han = hf.BertNormalizer(
    lowercase=False, strip_accents=False, clean_text=False
)
reference_nfd = hf.NFD()
reference_nfc = hf.NFC()
from pathlib import Path as LicensePath

# Resolve the shared license renderer independently of invocation directory.
repository_root = next(
    parent
    for parent in LicensePath(__file__).resolve().parents
    if (parent / "scripts/generated_source_licenses.py").is_file()
)
sys.path.insert(0, str(repository_root / "scripts"))
from pathlib import Path

from generated_source_licenses import unicode_source_header

if ud.unidata_version != "15.0.0":
    raise SystemExit(f"expected Unicode 15.0.0, got {ud.unidata_version}")

decompositions, combining, compositions = [], [], []
for cp in range(0x110000):
    ch = chr(cp)
    if ud.combining(ch):
        combining.append((cp, ud.combining(ch)))
    raw = ud.decomposition(ch)
    if raw and not raw.startswith("<"):
        parts = [int(value, 16) for value in raw.split()]
        if not 1 <= len(parts) <= 2:
            raise SystemExit(f"unexpected canonical decomposition U+{cp:04X}")
        decompositions.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
        if len(parts) == 2 and ud.normalize("NFC", "".join(map(chr, parts))) == ch:
            compositions.append(((parts[0] << 21) | parts[1], cp))

lines = [
    "// Generated by tools/generate_unicode_nfc.py; do not edit by hand.",
    "// Canonical data: Unicode 15.0.0, CPython unicodedata. Hangul is algorithmic.",
    "// WordPiece classifications and canonical exceptions: tokenizers 0.22.1.",
    'pub const unicode_version = "15.0.0";',
    "pub const Decomposition = struct { cp: u21, first: u21, second: u21 };",
    "pub const Combining = struct { cp: u21, value: u8 };",
    "pub const Composition = struct { pair: u64, cp: u21 };",
    "pub const decompositions = [_]Decomposition{",
]
lines += [
    f"    .{{ .cp = 0x{cp:x}, .first = 0x{a:x}, .second = 0x{b:x} }},"
    for cp, a, b in decompositions
]
lines += ["};", "pub const combining = [_]Combining{"]
lines += [f"    .{{ .cp = 0x{cp:x}, .value = {value} }}," for cp, value in combining]
lines += ["};", "pub const compositions = [_]Composition{"]
lines += [
    f"    .{{ .pair = 0x{pair:x}, .cp = 0x{cp:x} }},"
    for pair, cp in sorted(compositions)
]
lines += [
    "};",
    "pub const Lowercase = struct { cp: u21, values: []const u21 };",
    "pub const lowercase = [_]Lowercase{",
]
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    lowered = reference_lower.normalize_str(chr(cp))
    if lowered != chr(cp):
        values = ", ".join(f"0x{ord(ch):x}" for ch in lowered)
        array = f"&.{{{values}}}" if len(lowered) == 1 else f"&.{{ {values} }}"
        lines.append(f"    .{{ .cp = 0x{cp:x}, .values = {array} }},")
lines += ["};", "pub const Range = struct { first: u21, last: u21 };"]


# The reference uses several Unicode library versions. Derive its actual
# BERT classifications rather than assuming CPython categories are identical.
def scalar(cp):
    return cp < 0x110000 and not 0xD800 <= cp <= 0xDFFF


def ranges(name, predicate):
    lines.append(f"pub const {name} = [_]Range{{")
    start = None
    for cp in range(0x110001):
        included = scalar(cp) and predicate(cp)
        if included and start is None:
            start = cp
        elif not included and start is not None:
            lines.append(f"    .{{ .first = 0x{start:x}, .last = 0x{cp - 1:x} }},")
            start = None
    lines.append("};")


ranges("nonspacing_marks", lambda cp: reference_bert_marks.normalize_str(chr(cp)) == "")
ranges("strip_accents_marks", lambda cp: reference_marks.normalize_str(chr(cp)) == "")
ranges("controls", lambda cp: reference_clean.normalize_str(chr(cp)) == "")
ranges("spaces", lambda cp: reference_clean.normalize_str(chr(cp)) == " ")
ranges("chinese", lambda cp: reference_han.normalize_str(chr(cp)) != chr(cp))

# Preserve generic NFC's Unicode 15 behavior; WordPiece uses reference-specific
# exceptions. Fail generation if an exception is not a simple unassigned scalar.
decomposition_ignored = set()
for cp in range(0x110000):
    if not scalar(cp):
        continue
    char = chr(cp)
    expected = reference_nfd.normalize_str(char)
    if expected != ud.normalize("NFD", char):
        assert expected == char, (hex(cp), expected)
        decomposition_ignored.add(cp)
ranges("bert_decomposition_ignored", lambda cp: cp in decomposition_ignored)
combining_zero = set()
for cp in range(0x110000):
    if (
        not scalar(cp)
        or not ud.combining(chr(cp))
        or reference_nfd.normalize_str(chr(cp)) != chr(cp)
    ):
        continue
    probe = "\u0345" + chr(cp) + "\u0334"
    actual = reference_nfd.normalize_str(probe)
    if actual != ud.normalize("NFD", probe):
        assert actual == probe, (hex(cp), actual)
        combining_zero.add(cp)
ranges("bert_combining_zero", lambda cp: cp in combining_zero)
# All remaining canonical compositions must agree, including exclusions.
for pair, cp in compositions:
    actual = reference_nfc.normalize_str(chr(pair >> 21) + chr(pair & ((1 << 21) - 1)))
    assert actual == chr(cp) or cp in decomposition_ignored, hex(cp)
lines.append("")
output = Path(__file__).resolve().parents[1] / "src" / "unicode_nfc_data.zig"
data = (unicode_source_header(__file__) + "\n".join(lines)).encode()
output.write_bytes(data)
print(f"{output}: {len(data)} bytes sha256={hashlib.sha256(data).hexdigest()}")
