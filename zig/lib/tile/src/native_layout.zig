//! Dense row transforms shared by native CUDA/Metal compatibility exports.
//! One element per thread; no scratch, barriers, or arithmetic approximations.
//! ABI names are bindings, never a second copy of the indexing algorithm.
const std = @import("std");

pub const Transpose = struct {
    rows_per_group: u32,
    pub const tile = 32;
    pub const scratch_bytes = tile * (tile + 1) * @sizeOf(f32);
    pub fn threads(comptime p: Transpose) u32 {
        if (p.rows_per_group == 0 or tile % p.rows_per_group != 0) @compileError("transpose rows must divide its tile");
        return tile * p.rows_per_group;
    }
    pub fn physicalThreads(comptime p: Transpose, comptime flattened: bool) [3]u32 {
        return if (flattened) .{ p.threads(), 1, 1 } else .{ tile, p.rows_per_group, 1 };
    }
    pub fn grid(rows: usize, cols: usize, batch: usize) error{InvalidLayout}![3]usize {
        const x = cols / tile + @intFromBool(cols % tile != 0);
        const y = rows / tile + @intFromBool(rows % tile != 0);
        _ = std.math.mul(usize, x, y) catch return error.InvalidLayout;
        if (x > std.math.maxInt(u32) or y > std.math.maxInt(u32) or batch > std.math.maxInt(u32)) return error.InvalidLayout;
        return .{ x, y, batch };
    }
    pub const Native = struct {
        integer: []const u8,
        shared: []const u8,
        barrier: []const u8,
        rows: []const u8,
        cols: []const u8,
        x: []const u8,
        y: []const u8,
        group_x: []const u8,
        group_y: []const u8,
        base: []const u8 = "0u",
    };
    pub fn native(comptime p: Transpose, comptime n: Native) []const u8 {
        _ = p.threads();
        return @import("source_template.zig").render(
            \\    {{shared}} float tile[{{tile}}][{{padded}}];
            \\    {{u}} tx = {{x}}, ty = {{y}};
            \\    {{u}} tile_x = {{group_x}}, tile_y = {{group_y}};
            \\    {{u}} base = {{base}};
            \\    {{u}} input_x = tile_x * {{tile}}u + tx;
            \\    {{u}} input_y = tile_y * {{tile}}u + ty;
            \\{{#loop}}    #pragma unroll
            \\{{/loop}}    for ({{u}} offset = 0u; offset < {{tile}}u; offset += {{step}}u) {
            \\        if (input_x < {{cols}} && input_y + offset < {{rows}})
            \\            tile[ty + offset][tx] = input[base + (input_y + offset) * {{cols}} + input_x];
            \\    }
            \\    {{barrier}}
            \\    {{u}} output_x = tile_y * {{tile}}u + tx;
            \\    {{u}} output_y = tile_x * {{tile}}u + ty;
            \\{{#loop}}    #pragma unroll
            \\{{/loop}}    for ({{u}} offset = 0u; offset < {{tile}}u; offset += {{step}}u) {
            \\        if (output_x < {{rows}} && output_y + offset < {{cols}})
            \\            output[base + (output_y + offset) * {{rows}} + output_x] = tile[tx][ty + offset];
            \\    }
            \\
        , .{ .tile = std.fmt.comptimePrint("{d}", .{tile}), .padded = std.fmt.comptimePrint("{d}", .{tile + 1}), .shared = n.shared, .u = n.integer, .x = n.x, .y = n.y, .group_x = n.group_x, .group_y = n.group_y, .base = n.base, .rows = n.rows, .cols = n.cols, .barrier = n.barrier, .loop = p.rows_per_group < tile, .step = std.fmt.comptimePrint("{d}", .{p.rows_per_group}) });
    }
};
pub const cuda_transpose = Transpose{ .rows_per_group = 8 };
pub const metal_transpose = Transpose{ .rows_per_group = 32 };
pub const transpose_contract_header = std.fmt.comptimePrint(
    "// Generated by tile-kernel-codegen; do not edit.\n#pragma once\n#define ANTFLY_TRANSPOSE_TILE {d}u\n#define ANTFLY_TRANSPOSE_METAL_ROWS {d}u\n#define ANTFLY_TRANSPOSE_CUDA_THREADS {d}u\n",
    .{ Transpose.tile, metal_transpose.rows_per_group, cuda_transpose.threads() },
);

pub const Windows = struct {
    direction: enum { pack, unpack },
    pub const Native = struct {
        integer: []const u8,
        prefix: []const u8,
        index: []const u8,
        input: []const u8,
        output: []const u8,
        supplied_geometry: bool = false,
    };
    pub fn native(comptime w: Windows, comptime n: Native) []const u8 {
        return @import("source_template.zig").render(if (w.direction == .pack) pack else unpack, .{
            .u = n.integer,
            .p = n.prefix,
            .i = n.index,
            .input = n.input,
            .output = n.output,
            .supplied = n.supplied_geometry,
        });
    }
    const pack =
        \\{{^supplied}}    {{u}} windows_h = {{p}}padded_h / {{p}}window_size;
        \\    {{u}} windows_w = {{p}}padded_w / {{p}}window_size;
        \\{{/supplied}}
        \\    {{u}} area = {{#supplied}}{{p}}window_area{{/supplied}}{{^supplied}}{{p}}window_size * {{p}}window_size{{/supplied}};
        \\    {{u}} windows = {{#supplied}}{{p}}window_count{{/supplied}}{{^supplied}}{{p}}batch * windows_h * windows_w{{/supplied}};
        \\    {{u}} total = windows * area * {{p}}dim;
        \\    if ({{i}} >= total{{#supplied}} || {{p}}dim == 0u || {{p}}window_size == 0u{{/supplied}}) return;
        \\    {{u}} feature = {{i}} % {{p}}dim;
        \\    {{u}} token = {{i}} / {{p}}dim;
        \\    {{u}} position = token % area, win = token / area;
        \\{{#supplied}}    {{u}} windows_w = {{p}}padded_w / {{p}}window_size, windows_h = {{p}}padded_h / {{p}}window_size;
        \\    {{u}} windows_per_batch = windows_h * windows_w;
        \\    {{u}} b = win / windows_per_batch, remaining = win - b * windows_per_batch;
        \\    {{u}} wy = remaining / windows_w, wx = remaining - wy * windows_w;
        \\    {{u}} dy = position / {{p}}window_size, dx = position - dy * {{p}}window_size;
        \\    {{u}} y = wy * {{p}}window_size + dy, x = wx * {{p}}window_size + dx;
        \\{{/supplied}}{{^supplied}}    {{u}} b = win / (windows_h * windows_w);
        \\    {{u}} wy = (win / windows_w) % windows_h, wx = win % windows_w;
        \\    {{u}} y = wy * {{p}}window_size + position / {{p}}window_size;
        \\    {{u}} x = wx * {{p}}window_size + position % {{p}}window_size;
        \\{{/supplied}}
        \\    {{output}}[{{i}}] = ({{#supplied}}b < {{p}}batch && {{/supplied}}y < {{p}}height && x < {{p}}width) ? {{input}}[((b * {{p}}height + y) * {{p}}width + x) * {{p}}dim + feature] : 0.0f;
        \\
    ;
    const unpack =
        \\    {{u}} total = {{p}}batch * {{p}}height * {{p}}width * {{p}}dim;
        \\    if ({{i}} >= total{{#supplied}} || {{p}}dim == 0u || {{p}}window_size == 0u{{/supplied}}) return;
        \\    {{u}} feature = {{i}} % {{p}}dim;
        \\    {{u}} token = {{i}} / {{p}}dim;
        \\    {{u}} x = token % {{p}}width;
        \\    token /= {{p}}width;
        \\    {{u}} y = token % {{p}}height, b = token / {{p}}height;
        \\    {{u}} windows_w = {{p}}padded_w / {{p}}window_size;
        \\    {{u}} win = (b * ({{p}}padded_h / {{p}}window_size) + y / {{p}}window_size) * windows_w + x / {{p}}window_size;
        \\    {{u}} position = (y % {{p}}window_size) * {{p}}window_size + x % {{p}}window_size;
        \\    {{u}} source = win * {{#supplied}}{{p}}window_area{{/supplied}}{{^supplied}}{{p}}window_size * {{p}}window_size{{/supplied}} + position;
        \\    {{output}}[{{i}}] = {{input}}[source * {{p}}dim + feature];
        \\
    ;
};

pub const Operation = enum { slice, repeat, take, concat, first_match };
pub const Program = struct {
    operation: Operation,

    pub const Args = struct {
        input: []const f32,
        output: []f32,
        rows: usize,
        cols: usize,
        mask: []const i64 = &.{},
        sequence: usize = 0,
        words: usize = 0,
        seen: []u8 = &.{},
    };

    /// Token-major CPU first-match schedule. Other CPU transforms already use
    /// layout.copyRows/gatherRows; do not maintain another scalar copy engine.
    pub fn run(comptime p: Program, a: Args) error{InvalidLayout}!void {
        if (p.operation != .first_match) @compileError("use layout views for CPU row transforms");
        const mul = struct {
            fn checked(x: usize, y: usize) error{InvalidLayout}!usize {
                return std.math.mul(usize, x, y) catch error.InvalidLayout;
            }
        }.checked;
        if (a.output.len != try mul(a.rows, a.cols)) return error.InvalidLayout;
        if (a.words == 0) {
            if (a.rows != 0) return error.InvalidLayout;
            return;
        }
        if (a.rows % a.words != 0) return error.InvalidLayout;
        const tokens = try mul(a.rows / a.words, a.sequence);
        if (a.mask.len != tokens or a.input.len < try mul(tokens, a.cols) or a.seen.len != a.rows) return error.InvalidLayout;
        // CPU keeps the qualified token-major scan and row memcpy,
        // rather than repeating a sequence scan for every coordinate.
        @memset(a.output, 0);
        @memset(a.seen, 0);
        for (a.mask, 0..) |word_id, source| {
            if (word_id <= 0) continue;
            const word: usize = std.math.cast(usize, word_id - 1) orelse continue;
            if (word >= a.words) continue;
            const row = (source / a.sequence) * a.words + word;
            if (a.seen[row] != 0) continue;
            @memcpy(a.output[row * a.cols ..][0..a.cols], a.input[source * a.cols ..][0..a.cols]);
            a.seen[row] = 1;
        }
    }

    pub const Native = struct {
        integer: []const u8,
        index: []const u8,
        input: []const u8 = "input",
        second: []const u8 = "b",
        output: []const u8 = "output",
        rows: []const u8,
        cols: []const u8,
        source_rows: []const u8 = "source_rows",
        source_cols: []const u8 = "cols",
        second_cols: []const u8 = "dim_b",
        start: []const u8 = "start",
        ids: []const u8 = "row_ids",
        // Preserve row-bounded Metal slices, including their U32 overflow policy.
        row_bounds: bool = false,
        branch_concat: bool = false,
        sequence: []const u8 = "seq_len",
        words: []const u8 = "num_words",
        mask: []const u8 = "words_mask",
        mask_type: []const u8 = "long long",
    };

    /// Existing native launchers retain their ABI and U32 addressing. The only
    /// dialect choices here are type spelling and runtime parameter bindings.
    pub fn native(comptime p: Program, comptime n: Native) []const u8 {
        const fmt = std.fmt.comptimePrint;
        const u = n.integer;
        const guard = if (n.row_bounds)
            fmt("    if ({s} == 0u) return;\n    {s} row = {s} / {s};\n    {s} col = {s} - row * {s};\n    if (row >= {s}) return;\n", .{ n.cols, u, n.index, n.cols, u, n.index, n.cols, n.rows })
        else
            fmt("    {s} count = {s} * {s};\n    if ({s} >= count) return;\n    {s} row = {s} / {s};\n    {s} col = {s} - row * {s};\n", .{ u, n.rows, n.cols, n.index, u, n.index, n.cols, u, n.index, n.cols });
        const body = switch (p.operation) {
            .slice => fmt("    {s}[{s}] = {s}[row * {s} + {s} + col];\n", .{ n.output, n.index, n.input, n.source_cols, n.start }),
            .repeat => fmt("    {s}[{s}] = {s}[col];\n", .{ n.output, n.index, n.input }),
            .take => fmt("    {s} src_row = {s}[row];\n    {s}[{s}] = src_row < {s} ? {s}[src_row * {s} + col] : 0.0f;\n", .{ u, n.ids, n.output, n.index, n.source_rows, n.input, n.cols }),
            .concat => if (n.branch_concat)
                fmt("    if (col < {s}) {{\n        {s}[{s}] = {s}[row * {s} + col];\n    }} else {{\n        {s}[{s}] = {s}[row * {s} + (col - {s})];\n    }}\n", .{ n.source_cols, n.output, n.index, n.input, n.source_cols, n.output, n.index, n.second, n.second_cols, n.source_cols })
            else
                fmt("    {s}[{s}] = col < {s} ? {s}[row * {s} + col] : {s}[row * {s} + (col - {s})];\n", .{ n.output, n.index, n.source_cols, n.input, n.source_cols, n.second, n.second_cols, n.source_cols }),
            .first_match => fmt(
                "    {s} word = row % {s};\n    {s} batch_index = row / {s};\n    {s} wanted = ({s})(word + 1u);\n    {s} token_base = batch_index * {s};\n    {s} hidden_base = token_base * {s} + col;\n    for ({s} token = 0u; token < {s}; ++token) {{\n        if ({s}[token_base + token] == wanted) {{\n            {s}[{s}] = {s}[hidden_base + token * {s}];\n            return;\n        }}\n    }}\n    {s}[{s}] = 0.0f;\n",
                .{ u, n.words, u, n.words, n.mask_type, n.mask_type, u, n.sequence, u, n.cols, u, n.sequence, n.mask, n.output, n.index, n.input, n.cols, n.output, n.index },
            ),
        };
        return guard ++ body;
    }
};
