"""Generate default Unicode 16.0.0 casing tables, without locale tailoring.

Download UnicodeData.txt, SpecialCasing.txt, and DerivedCoreProperties.txt from
https://www.unicode.org/Public/16.0.0/ucd/ then run:
  python3 generate_unicode_case.py INPUT_DIRECTORY OUTPUT_ZIG
Input hashes are pinned; generation never depends on Python's Unicode version.
"""

import hashlib
import sys
from pathlib import Path

repository_root = next(
    p
    for p in Path(__file__).resolve().parents
    if (p / "scripts/generated_source_licenses.py").is_file()
)
sys.path.insert(0, str(repository_root / "scripts"))
from generated_source_licenses import unicode_source_header

HASHES = {
    "UnicodeData.txt": "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f",
    "SpecialCasing.txt": "8d5de354eef79f2395a54c9c7dcebbaf3d30fc962d0f85611ea97aa973a0c451",
    "DerivedCoreProperties.txt": "39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd",
}


def generate(directory):
    inputs = {}
    for name, digest in HASHES.items():
        raw = (directory / name).read_bytes()
        if hashlib.sha256(raw).hexdigest() != digest:
            raise ValueError(f"unexpected Unicode 16.0.0 input: {name}")
        inputs[name] = raw.decode().splitlines()
    lower, upper = {}, {}
    for line in inputs["UnicodeData.txt"]:
        fields = line.split(";")
        cp = int(fields[0], 16)
        for mapping, index in ((lower, 13), (upper, 12)):
            if fields[index]:
                mapping[cp] = [int(fields[index], 16)]
    for raw in inputs["SpecialCasing.txt"]:
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [part.strip() for part in line.split(";")]
        if fields[4]:
            # Final_Sigma is implemented over the original string at runtime.
            # The remaining conditions are locale tailorings, intentionally omitted.
            if fields[4] not in (
                "Final_Sigma",
                "lt",
                "lt After_Soft_Dotted",
                "lt More_Above",
                "tr",
                "az",
                "tr After_I",
                "az After_I",
                "tr Not_Before_Dot",
                "az Not_Before_Dot",
            ):
                raise ValueError(f"unhandled casing condition: {fields[4]}")
            continue
        cp = int(fields[0], 16)
        lower[cp] = [int(part, 16) for part in fields[1].split()]
        upper[cp] = [int(part, 16) for part in fields[3].split()]
    lines = [
        "// Generated by tools/generate_unicode_case.py; do not edit.",
        "// Unicode 16.0.0 default full case mappings and casing properties.",
        'pub const unicode_version = "16.0.0";',
        "pub const Mapping = struct { cp: u21, text: []const u8 };",
        "pub const Range = struct { first: u21, last: u21 };",
    ]
    for name, mapping in (("lower", lower), ("upper", upper)):
        lines.append(f"pub const {name} = [_]Mapping{{")
        for cp, points in sorted(mapping.items()):
            if points == [cp]:
                continue
            encoded = "".join(
                f"\\x{byte:02x}" for point in points for byte in chr(point).encode()
            )
            lines.append(f'    .{{ .cp = 0x{cp:x}, .text = "{encoded}" }},')
        lines.append("};")
    for prop, name in (("Cased", "cased"), ("Case_Ignorable", "ignorable")):
        lines.append(f"pub const {name} = [_]Range{{")
        for raw in inputs["DerivedCoreProperties.txt"]:
            fields = [part.strip() for part in raw.split("#", 1)[0].split(";")]
            if len(fields) != 2 or fields[1] != prop:
                continue
            bounds = fields[0].split("..")
            first, last = int(bounds[0], 16), int(bounds[-1], 16)
            lines.append(f"    .{{ .first = 0x{first:x}, .last = 0x{last:x} }},")
        lines.append("};")
    return unicode_source_header(__file__) + "\n".join(lines) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    Path(sys.argv[2]).write_text(generate(Path(sys.argv[1])))
