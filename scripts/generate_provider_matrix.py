"""Generate the provider x component matrix in the inference providers guide.

The provider enums in the OpenAPI specs (and the reader enum, which lives in
Zig) are the source of truth for which provider can serve which kind of
inference component. Regenerating the table from them keeps the docs from
drifting when a provider is added or removed.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
GUIDE = ROOT / "docs/guides/inference-providers.mdx"
START = (
    "{/* provider-matrix:start (generated by scripts/generate_provider_matrix.py) */}"
)
END = "{/* provider-matrix:end */}"

# (column heading, link anchor on the guide, source)
KINDS: list[tuple[str, str, tuple[str, ...]]] = [
    (
        "Embedder",
        "embedder",
        ("specs/openapi/antfly/embeddings.yaml", "EmbedderProvider"),
    ),
    (
        "Reranker",
        "reranker",
        ("specs/openapi/antfly/reranking.yaml", "RerankerProvider"),
    ),
    ("Chunker", "chunker", ("specs/openapi/antfly/chunking.yaml", "ChunkerProvider")),
    ("Reader", "reader", ("zig/lib/readers/src/config.zig", "Provider")),
    ("Transcriber", "transcriber", ("specs/openapi/antfly/audio.yaml", "STTProvider")),
    (
        "Speech",
        "speech-synthesizer",
        ("specs/openapi/antfly/audio.yaml", "TTSProvider"),
    ),
    (
        "Generator",
        "generator",
        ("specs/openapi/shared/generating.yaml", "GeneratorProvider"),
    ),
    (
        "Extractor",
        "extractor",
        ("specs/openapi/ai/extraction.yaml", "ExtractionProvider"),
    ),
    (
        "Decider",
        "decider",
        ("specs/openapi/antfly/config.yaml", "DeciderConfig.provider"),
    ),
    (
        "Web search",
        "web-search",
        ("specs/openapi/antfly/websearch.yaml", "WebSearchProvider"),
    ),
]

EXCLUDED = {"mock"}

# Provider id -> (display name, provider page slug)
PAGES: dict[str, tuple[str, str]] = {
    "antfly": ("Antfly", "antfly"),
    "anthropic": ("Anthropic", "anthropic"),
    "apple": ("Apple", "apple"),
    "bedrock": ("AWS Bedrock", "bedrock"),
    "brave": ("Brave", "web-search"),
    "chatgpt": ("ChatGPT plan", "chatgpt"),
    "cloudflare": ("Cloudflare Workers AI", "cloudflare"),
    "cohere": ("Cohere", "cohere"),
    "elevenlabs": ("ElevenLabs", "elevenlabs"),
    "exa": ("Exa", "web-search"),
    "gemini": ("Gemini API", "google"),
    "jev": ("Jev (TypeSafe)", "jev"),
    "linkup": ("Linkup", "web-search"),
    "ollama": ("Ollama", "ollama"),
    "openai": ("OpenAI", "openai"),
    "openrouter": ("OpenRouter", "openrouter"),
    "pioneer": ("Pioneer", "pioneer"),
    "serper": ("Serper", "web-search"),
    "tavily": ("Tavily", "web-search"),
    "vertex": ("Google Vertex AI", "google"),
    "you": ("You.com", "web-search"),
}


def spec_enum(path: Path, name: str) -> list[str]:
    doc = yaml.safe_load(path.read_text())
    schemas = doc["components"]["schemas"]
    if "." in name:
        schema_name, prop = name.split(".", 1)
        return list(schemas[schema_name]["properties"][prop]["enum"])
    return list(schemas[name]["enum"])


def zig_enum(path: Path, name: str) -> list[str]:
    source = path.read_text()
    match = re.search(rf"pub const {name} = enum \{{(.*?)\n\n", source, re.S)
    if not match:
        raise SystemExit(f"{path}: enum {name} not found")
    return re.findall(r"^\s+([a-z_]+),\s*$", match.group(1), re.M)


def providers_for(source: tuple[str, ...]) -> list[str]:
    path = ROOT / source[0]
    values = (
        zig_enum(path, source[1])
        if path.suffix == ".zig"
        else spec_enum(path, source[1])
    )
    return [value for value in values if value not in EXCLUDED]


def render() -> str:
    support: dict[str, set[str]] = {}
    for heading, _, source in KINDS:
        for provider in providers_for(source):
            if provider not in PAGES:
                raise SystemExit(
                    f"provider {provider!r} has no page in {Path(__file__).name}"
                )
            support.setdefault(provider, set()).add(heading)

    order = ["antfly"] + sorted(
        (p for p in support if p != "antfly"), key=lambda p: PAGES[p][0].lower()
    )
    header = "| Provider | " + " | ".join(f"[{h}](#{a})" for h, a, _ in KINDS) + " |"
    divider = "|---|" + "|".join(":-:" for _ in KINDS) + "|"
    rows = []
    for provider in order:
        name, slug = PAGES[provider]
        cells = " | ".join(
            "✓" if heading in support[provider] else "" for heading, _, _ in KINDS
        )
        rows.append(
            f"| [{name}](/docs/guides/providers/{slug}) (`{provider}`) | {cells} |"
        )
    return "\n".join([START, "", header, divider, *rows, "", END])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if the committed table is stale"
    )
    args = parser.parse_args()

    text = GUIDE.read_text()
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit(
            f"{GUIDE.relative_to(ROOT)}: provider matrix markers not found"
        )
    updated = pattern.sub(lambda _: render(), text, count=1)
    if args.check:
        if updated != text:
            print(
                f"{GUIDE.relative_to(ROOT)} is stale; run `make provider-matrix-generate`",
                file=sys.stderr,
            )
            return 1
        return 0
    if updated != text:
        GUIDE.write_text(updated)
    return 0


if __name__ == "__main__":
    sys.exit(main())
