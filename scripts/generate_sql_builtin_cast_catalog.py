"""Reproduce immutable PostgreSQL builtin cast identities for native admission."""

import argparse
from pathlib import Path

from generate_sql_postgres_reference import postgres

TYPES = {
    "text": "text",
    "uuid": "uuid",
    "int16": "smallint",
    "int32": "integer",
    "int64": "bigint",
    "float32": "real",
    "float64": "double precision",
    "boolean": "boolean",
    "jsonb": "jsonb",
    "numeric": "numeric",
    "date": "date",
    "time": "time",
    "time_tz": "timetz",
    "timestamp": "timestamp",
    "timestamp_tz": "timestamptz",
    "interval": "interval",
    "numrange": "numrange",
    "daterange": "daterange",
    "tsrange": "tsrange",
    "tstzrange": "tstzrange",
}


def render():
    with postgres() as connection:
        pairs = []
        with connection.cursor() as cursor:
            for native, spelling in TYPES.items():
                cursor.execute("SELECT %s::regtype::oid", (spelling,))
                pairs.append((native, cursor.fetchone()[0]))
            cursor.execute(
                "SELECT castsource,casttarget FROM pg_cast ORDER BY castsource,casttarget"
            )
            builtin = set(cursor.fetchall())
    header = Path(__file__).with_name("license-header-apache.txt").read_text()
    lines = [
        "// " + line if line else "//" for line in header.rstrip("\n").splitlines()
    ]
    lines.extend(
        [
            "",
            "// Generated by scripts/generate_sql_builtin_cast_catalog.py from PostgreSQL 18.",
            "// Automatic I/O and array coercions are not pg_cast objects.",
            "pub fn exists(pair: anytype) bool {",
            "    if (pair.source.array or pair.target.array) return false;",
            "    return switch (pair.source.scalar) {",
        ]
    )
    for source, source_oid in pairs:
        targets = [
            target
            for target, target_oid in pairs
            if (source_oid, target_oid) in builtin
        ]
        if targets:
            lines.extend(
                [
                    f"        .{source} => switch (pair.target.scalar) {{",
                    "            "
                    + ", ".join(f".{target}" for target in targets)
                    + " => true,",
                    "            else => false,",
                    "        },",
                ]
            )
    lines.extend(["        else => false,", "    };", "}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        assert args.output.read_text() == expected, (
            "PostgreSQL builtin cast catalog drift"
        )
    else:
        args.output.write_text(expected)


if __name__ == "__main__":
    main()
