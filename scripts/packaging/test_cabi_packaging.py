    def test_npm_publish_is_retry_safe_and_rejects_content_drift(self) -> None:
        helper = REPO_ROOT / "scripts" / "packaging" / "publish_npm_package.sh"
        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            fake_bin = root / "bin"
            fake_bin.mkdir()
            npm = fake_bin / "npm"
            npm.write_text(
                "#!/bin/sh\n"
                "printf '%s\\n' \"$*\" >> \"$FAKE_NPM_LOG\"\n"
            )
            npm.chmod(0o755)
            python = fake_bin / "python3"
            python.write_text(
                "#!/bin/sh\n"
                "case \"$*\" in\n"
                "  *npm-integrity*) printf '%s\\n' \"${FAKE_NPM_INTEGRITY:-}\" ;;\n"
                "  *npm-tag*) printf '%s\\n' \"${FAKE_NPM_TAG:-}\" ;;\n"
                "  *) exit 2 ;;\n"
                "esac\n"
            )
            python.chmod(0o755)
            tarball = root / "package.tgz"
            tarball.write_bytes(b"npm package")
            digest = base64.b64encode(hashlib.sha512(tarball.read_bytes()).digest()).decode()
            integrity = f"sha512-{digest}"
            log = root / "npm.log"
            env = {
                **os.environ,
                "PATH": f"{fake_bin}:{os.environ['PATH']}",
                "FAKE_NPM_LOG": str(log),
                "FAKE_NPM_INTEGRITY": integrity,
                "FAKE_NPM_TAG": "1.2.3",
            }
            command = ["sh", str(helper), "@antfly/cli", "1.2.3", "latest", str(tarball)]

            subprocess.run(command, check=True, env=env, capture_output=True, text=True)
            self.assertFalse(log.exists())

            env["FAKE_NPM_INTEGRITY"] = "sha512-different"
            mismatch = subprocess.run(command, env=env, capture_output=True, text=True, check=False)
            self.assertNotEqual(mismatch.returncode, 0)
            self.assertIn("exists with different contents", mismatch.stderr)

            env["FAKE_NPM_INTEGRITY"] = integrity
            env["FAKE_NPM_TAG"] = "1.2.2"
            alias_drift = subprocess.run(command, env=env, capture_output=True, text=True, check=False)
            self.assertNotEqual(alias_drift.returncode, 0)
            self.assertIn("dist-tag latest points", alias_drift.stderr)

            env["FAKE_NPM_INTEGRITY"] = ""
            env["FAKE_NPM_TAG"] = "1.2.3"
            subprocess.run(command, check=True, env=env, capture_output=True, text=True)
            self.assertIn("publish", log.read_text())

    def test_python_and_npm_packages_preserve_cabi_artifacts(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            repo = root / "repo"
            extracted = root / "extracted"
            out = root / "out"
            archive_dir = root / "archives"
            archive_dir.mkdir()

            platform = package_cli_release.PLATFORMS[1]
            write_release_archive(
                archive_dir,
                "1.2.3",
                platform.release_os,
                platform.release_arch,
                platform.release_variant,
            )

            package_dir = repo / "ts" / "packages" / platform.npm_package_dir
            package_dir.mkdir(parents=True)
            (package_dir / "package.json").write_text(
                json.dumps(
                    {
                        "name": f"@antfly/{platform.npm_package_dir}",
                        "version": "0.0.0",
                        "files": ["bin", "include", "lib", "share", "README.md"],
                        "libc": [platform.npm_libc],
                    }
                )
                + "\n"
            )
            (repo / "zig" / "pkg" / "antfly" / "antfarm").mkdir(parents=True)
            (repo / "zig" / "pkg" / "antfly" / "antfarm" / "index.html").write_text("antfarm\n")
            (repo / "py" / "packages" / "cli" / "src" / "antfly_cli").mkdir(parents=True)
            (repo / "py" / "packages" / "cli" / "src" / "antfly_cli" / "__init__.py").write_text(
                "def main(): return 0\n"
            )
            (repo / "py" / "packages" / "cli" / "pyproject.toml").write_text(
                '[project]\nname = "antfly-cli"\nrequires-python = ">=3.10"\n'
            )

            package_cli_release.extract_archive(archive_dir, "1.2.3", platform, extracted)
            package_cli_release.copy_antfarm(repo, extracted)
            package_cli_release.populate_npm_package(repo, platform, extracted)

            npm_package = repo / "ts" / "packages" / platform.npm_package_dir
            self.assertEqual((npm_package / "include" / "antfly.h").read_text(), "/* antfly header */\n")
            self.assertEqual((npm_package / "lib" / "libantfly.so").read_text(), "antfly library\n")

            wheel = package_cli_release.package_python_wheel(repo, out, "1.2.3", platform, extracted)
            with zipfile.ZipFile(wheel) as zf:
                names = set(zf.namelist())
                metadata = zf.read("antfly_cli-1.2.3.dist-info/METADATA").decode()
            self.assertIn("antfly_cli/include/antfly.h", names)
            self.assertIn("antfly_cli/lib/libantfly.so", names)
            self.assertIn("antfly_cli/share/antfly/asset.txt", names)
            self.assertIn("Requires-Python: >=3.10", metadata)

