"""Generate the SDK's small runtime receipt enums from the public OpenAPI spec."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "ts/packages/sdk/src/sql-catalog-contract.generated.ts"


def render() -> str:
    schemas = yaml.safe_load((ROOT / "specs/openapi/antfly/metadata.yaml").read_text())[
        "components"
    ]["schemas"]
    header = "\n".join(
        "//" + line[1:] if line.startswith("#") else line
        for line in Path(__file__).read_text().split('"""', 1)[0].splitlines()[1:]
    ).rstrip()
    parts = [
        header,
        "",
        "// Generated by scripts/generate_sql_catalog_contract.py; do not edit.",
        "",
    ]
    for name, schema in (
        ("sqlCatalogObjectKinds", "SQLCatalogObjectKind"),
        ("sqlCatalogOperationKinds", "SQLCatalogOperationKind"),
        ("sqlCatalogOperationStates", "SQLCatalogOperationState"),
    ):
        values = schemas[schema]["enum"]
        if (
            not values
            or len(values) != len(set(values))
            or not all(isinstance(value, str) for value in values)
        ):
            raise ValueError(f"Invalid enum: {schema}")
        inline = f"export const {name} = {json.dumps(values)} as const;"
        if len(inline) <= 100:
            parts.append(inline)
        else:
            parts.extend(
                [
                    f"export const {name} = [",
                    *(f"  {json.dumps(value)}," for value in values),
                    "] as const;",
                ]
            )
        parts.append("")
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit(
                "SQL catalog runtime contract is stale; run make sql-catalog-contract-generate"
            )
    else:
        OUTPUT.write_text(expected)


if __name__ == "__main__":
    main()
