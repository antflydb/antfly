"""Generate portable source-management models from the shared OpenAPI contract."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMAS = json.loads((ROOT / "specs/openapi/sources/management.yaml").read_text())[
    "components"
]["schemas"]


def typ(schema, language):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "enum" in schema and language != "rs":
        values = [json.dumps(v) for v in schema["enum"]]
        return (
            " | ".join(values)
            if language == "ts"
            else "Literal[" + ", ".join(values) + "]"
        )
    kind = schema.get("type")
    if kind == "array":
        inner = typ(schema["items"], language)
        return {"ts": f"Array<{inner}>", "py": f"list[{inner}]", "rs": f"Vec<{inner}>"}[
            language
        ]
    return {
        "ts": {
            "string": "string",
            "integer": "number",
            "boolean": "boolean",
            "object": "Record<string, unknown>",
        },
        "py": {
            "string": "str",
            "integer": "int",
            "boolean": "bool",
            "object": "dict[str, Any]",
        },
        "rs": {
            "string": "String",
            "integer": "i64",
            "boolean": "bool",
            "object": "serde_json::Map<String, serde_json::Value>",
        },
    }[language][kind]


def render(language):
    notice = (
        (ROOT / "go/pkg/sources/document.go")
        .read_text()
        .split("package sources", 1)[0]
        .rstrip()
    )
    if language == "py":
        notice = "\n".join(
            "#" + line[2:] if line.startswith("//") else line
            for line in notice.splitlines()
        )
    lines = {
        "ts": ["// Generated by scripts/generate_sources_clients.py. DO NOT EDIT.", ""],
        "py": [
            "# Generated by scripts/generate_sources_clients.py. DO NOT EDIT.",
            "from __future__ import annotations",
            "from typing import Any, Literal, NotRequired, TypedDict",
            "",
        ],
        "rs": [
            "// Generated by scripts/generate_sources_clients.py. DO NOT EDIT.",
            "use serde::{Deserialize, Serialize};",
            "",
        ],
    }[language]
    for name, schema in SCHEMAS.items():
        if "$ref" in schema:
            if language == "py":
                lines.append("")
            target = typ(schema, language)
            lines.append(
                {
                    "ts": f"export type {name} = {target};",
                    "py": f"{name} = {target}",
                    "rs": f"pub type {name} = {target};",
                }[language]
            )
            lines.append("")
            continue
        if language == "py":
            lines.append("")
        required = set(schema.get("required", []))
        lines.extend(
            {
                "ts": [f"export interface {name} {{"],
                "py": [f"class {name}(TypedDict):"],
                "rs": [
                    "#[derive(Debug, Clone, Serialize, Deserialize)]",
                    f"pub struct {name} {{",
                ],
            }[language]
        )
        for field, definition in schema["properties"].items():
            value = typ(definition, language)
            optional = field not in required
            if language == "ts":
                lines.append(f"  {field}{'?' if optional else ''}: {value};")
            elif language == "py":
                lines.append(
                    f"    {field}: {'NotRequired[' + value + ']' if optional else value}"
                )
            else:
                if optional:
                    lines.append(
                        '    #[serde(default, skip_serializing_if = "Option::is_none")]'
                    )
                lines.append(
                    f"    pub {field}: {'Option<' + value + '>' if optional else value},"
                )
        if language != "py":
            lines.append("}")
        lines.append("")
    return notice + "\n\n" + "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    targets = {
        "ts": "ts/packages/sdk/src/sources-types.d.ts",
        "py": "py/packages/sdk/src/antfly/sources_types.py",
        "rs": "rs/crates/sdk/src/sources_types.rs",
    }
    for language, target in targets.items():
        path = ROOT / target
        content = render(language)
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"{target} needs regeneration")
        else:
            path.write_text(content)
